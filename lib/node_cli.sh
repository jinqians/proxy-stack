_node_cli_set_value() {
    local json="$1" key="$2" value="$3" json_mode="${4:-0}"
    if [[ "$json_mode" == "1" ]]; then
        jq -c --arg k "$key" --argjson v "$value" '.[$k] = $v' <<<"$json"
        return
    fi
    jq -c --arg k "$key" --arg v "$value" '
      def typed:
        if ($k | test("^(port|public_port|version|up|down|insecure)$")) then ($v | tonumber)
        elif ($k | test("^(fallback_enabled|disable_pmtud)$")) then
          if $v == "true" or $v == "1" or $v == "yes" then true
          elif $v == "false" or $v == "0" or $v == "no" then false
          else error("invalid boolean") end
        elif $k == "short_ids" then
          if ($v | startswith("[")) then ($v | fromjson) else [$v] end
        else $v end;
      .[$k] = typed' <<<"$json"
}

_node_cli_load_input() {
    local spec="$1" content
    case "$spec" in
        -) content=$(command cat) ;;
        @*) content=$(command cat "${spec#@}") || return 1 ;;
        *)
            if [[ -f "$spec" ]]; then content=$(command cat "$spec") || return 1
            else content="$spec"
            fi
            ;;
    esac
    if ! printf '%s' "$content" | jq -e 'type == "object"' >/dev/null 2>&1; then
        _node_cli_err "input must be a JSON object"
        return 1
    fi
    printf '%s' "$content" | jq -c '.'
}

_node_cli_ss_password() {
    local method="$1" bytes=16
    case "$method" in *256*|*chacha20*) bytes=32 ;; esac
    openssl rand -base64 "$bytes" | tr -d '\n'
}

_node_cli_keypair() {
    local core="$1" proto="$2" module pair
    module=$(_node_cli_module_path "$core" "$proto")
    # shellcheck source=/dev/null
    source "$module"
    case "$core" in
        xray) pair=$(xray_gen_x25519_keys) || return 1 ;;
        sing-box) pair=$(sb_gen_reality_keys) || return 1 ;;
        mihomo) pair=$(mh_gen_reality_keys) || return 1 ;;
    esac
    printf '%s' "$pair"
}

_node_cli_defaults() {
    local core="$1" proto="$2" json="$3" port method pair private public sid mode
    port=$(printf '%s' "$json" | jq -r '.port // empty')
    json=$(printf '%s' "$json" | jq -c --arg tag_prefix "${core}-${proto}" \
        '.tag //= ($tag_prefix + "-1")') || return 1
    case "$proto" in
        reality)
            json=$(printf '%s' "$json" | jq -c \
                --arg uuid "$(uuid_gen)" --arg sid "$(openssl rand -hex 4)" '
                .uuid //= $uuid |
                .flow //= "xtls-rprx-vision" |
                .short_ids //= [$sid]') || return 1
            # 不给伪装目标兜底默认值。非交互路径没人可问，而任何写死的知名域名都可能
            # 是（或变成）多租户 CDN 前端，那会让 Reality 的回落把本机变成通往整个 CDN
            # 的免费中继。宁可让调用方显式指定，也不静默建出一个有洞的节点。
            local _sn _dest
            _sn=$(printf '%s' "$json"   | jq -r '.server_name // empty')
            _dest=$(printf '%s' "$json" | jq -r '.dest // empty')
            if [[ -z "$_sn" || -z "$_dest" ]]; then
                _node_cli_err "Reality camouflage target is required; pass --server-name and --dest (pick a single-tenant site, ideally in your own ASN — a target behind a shared CDN frontend lets anyone use this host as a free relay)"
                return 1
            fi
            # 与交互流程一致：命中共享前端时告警并给该节点打开回落限速兜底。
            local _dh _dp
            if [[ "$_dest" =~ ^\[([^]]+)\]:([0-9]+)$ ]]; then
                _dh="${BASH_REMATCH[1]}"; _dp="${BASH_REMATCH[2]}"
            else
                _dh="${_dest%:*}"; _dp="${_dest##*:}"
            fi
            if reality_dest_is_shared_frontend "$_dh" "$_dp"; then
                _node_cli_err "warning: dest ${_dest} is a shared CDN frontend (probe ${REALITY_DEST_SHARED_BY} got a valid certificate on the same IP); enabling REALITY fallback rate limiting for this node"
                json=$(printf '%s' "$json" | jq -c '.limit_fallback = true') || return 1
            fi
            if [[ "$core" == "xray" ]]; then
                json=$(printf '%s' "$json" | jq -c --arg p "$port" '
                  .listen_addr //= "0.0.0.0" |
                  .public_port //= ($p | tonumber) |
                  .server_names_raw //= .server_name') || return 1
            elif [[ "$core" == "mihomo" ]]; then
                json=$(printf '%s' "$json" | jq -c '.listen_addr //= "0.0.0.0"') || return 1
            else
                json=$(printf '%s' "$json" | jq -c '.listen_addr //= "::"') || return 1
            fi
            private=$(printf '%s' "$json" | jq -r '.private_key // empty')
            public=$(printf '%s' "$json" | jq -r '.public_key // empty')
            if [[ -z "$private" || -z "$public" ]]; then
                pair=$(_node_cli_keypair "$core" "$proto") || {
                    _node_cli_err "Reality keys are missing and $core could not generate them; pass --private-key and --public-key"
                    return 1
                }
                private=${pair%%$'\t'*}; public=${pair#*$'\t'}
                json=$(printf '%s' "$json" | jq -c --arg private "$private" --arg public "$public" \
                    '.private_key=$private | .public_key=$public') || return 1
            fi
            ;;
        vision)
            json=$(printf '%s' "$json" | jq -c --arg uuid "$(uuid_gen)" --arg p "$port" '
              .uuid //= $uuid | .flow //= "xtls-rprx-vision" |
              .listen_addr //= "0.0.0.0" | .public_port //= ($p | tonumber) |
              .fallback_enabled //= false') || return 1
            ;;
        trojan)
            # Trojan 的凭据是密码而非 UUID。Xray 侧走真实域名+证书（回落默认关闭，
            # 开启回落需要 Nginx 伪装站，那是交互流程才做的事）；sing-box / mihomo
            # 侧与 anytls 同构，需要 sni + 证书路径，非交互路径不代签证书，
            # 所以 cert_path / key_path 必须由调用方给出。
            if [[ "$core" == "xray" ]]; then
                json=$(printf '%s' "$json" | jq -c --arg pw "$(rand_str 20)" --arg p "$port" '
                  .password //= $pw |
                  .listen_addr //= "0.0.0.0" | .public_port //= ($p | tonumber) |
                  .fallback_enabled //= false') || return 1
            else
                local _listen_default="::"
                [[ "$core" == "mihomo" ]] && _listen_default="0.0.0.0"
                json=$(printf '%s' "$json" | jq -c --arg pw "$(rand_str 20)" --arg p "$port" \
                    --arg listen "$_listen_default" '
                  .password //= $pw | .insecure //= 0 |
                  .listen_addr //= $listen | .public_port //= ($p | tonumber)') || return 1
            fi
            ;;
        vless)
            # 传输默认裸 TLS（tcp）。Vision 的 flow 只在 tcp 下有意义，套进
            # ws/grpc/h2 客户端对不上，所以其它传输一律清空 flow。
            local _vl_listen="::"
            [[ "$core" == "mihomo" ]] && _vl_listen="0.0.0.0"
            json=$(printf '%s' "$json" | jq -c --arg uuid "$(uuid_gen)" --arg p "$port" \
                --arg path "$(rand_path)" --arg listen "$_vl_listen" '
              .uuid //= $uuid | .transport //= "tcp" | .path //= $path | .insecure //= 0 |
              .listen_addr //= $listen | .public_port //= ($p | tonumber) |
              .flow //= (if .transport == "tcp" then "xtls-rprx-vision" else "" end) |
              (if .transport != "tcp" then .flow = "" else . end)') || return 1
            ;;
        socks)
            # 默认只监听 127.0.0.1。SOCKS5 明文传输，公网暴露就是一个开放代理，
            # 非交互路径没人可以确认风险，所以默认值必须是保守的那个；要公网监听
            # 得显式传 --listen-addr 0.0.0.0，且那种情况下凭据不再可选。
            json=$(printf '%s' "$json" | jq -c --arg p "$port" '
              .listen_addr //= "127.0.0.1" | .public_port //= ($p | tonumber) |
              .username //= "" | .password //= "" | .udp //= true') || return 1
            if [[ "$(printf '%s' "$json" | jq -r '.listen_addr')" != "127.0.0.1" ]] \
               && [[ -z "$(printf '%s' "$json" | jq -r '.username')" ]]; then
                _node_cli_err "a public SOCKS5 listener requires credentials; pass --username and --password (the protocol is plaintext, so this only stops casual scanners)"
                return 1
            fi
            ;;
        vmess)
            # VMess 固定 WS+TLS，所以 path 是必填项（没有就随机一个）。
            # Xray 侧用真实证书域名 domain；sing-box / mihomo 侧与 trojan 同构，
            # 需要 sni + 证书路径，非交互路径不代签证书。
            if [[ "$core" == "xray" ]]; then
                json=$(printf '%s' "$json" | jq -c --arg uuid "$(uuid_gen)" --arg p "$port" \
                    --arg path "$(rand_path)" '
                  .uuid //= $uuid | .path //= $path |
                  .listen_addr //= "0.0.0.0" | .public_port //= ($p | tonumber)') || return 1
            else
                local _vm_listen="::"
                [[ "$core" == "mihomo" ]] && _vm_listen="0.0.0.0"
                json=$(printf '%s' "$json" | jq -c --arg uuid "$(uuid_gen)" --arg p "$port" \
                    --arg path "$(rand_path)" --arg listen "$_vm_listen" '
                  .uuid //= $uuid | .path //= $path | .insecure //= 0 |
                  .listen_addr //= $listen | .public_port //= ($p | tonumber)') || return 1
            fi
            ;;
        xhttp)
            json=$(printf '%s' "$json" | jq -c --arg uuid "$(uuid_gen)" --arg p "$port" --arg path "$(rand_path)" '
              .uuid //= $uuid | .mode //= "xhttp" | .path //= $path |
              .domain //= "" | .listen_addr //= "0.0.0.0" |
              .public_port //= ($p | tonumber) | .fallback_enabled //= false') || return 1
            mode=$(printf '%s' "$json" | jq -r '.mode')
            if [[ "$mode" == "mkcp" ]]; then
                json=$(printf '%s' "$json" | jq -c --arg seed "$(rand_str 16)" '
                  .kcp_seed //= $seed | .kcp_header //= "none"') || return 1
            fi
            if [[ "$mode" == "reality-layer" ]]; then
                sid=$(openssl rand -hex 4)
                json=$(printf '%s' "$json" | jq -c --arg sid "$sid" '.short_id //= $sid') || return 1
                # 与 reality 同理：reality-layer 的 dest 就是 server_name:443，不给兜底默认值。
                local _xsn; _xsn=$(printf '%s' "$json" | jq -r '.server_name // empty')
                if [[ -z "$_xsn" ]]; then
                    _node_cli_err "XHTTP reality-layer camouflage target is required; pass --server-name (its dest is <server-name>:443 — pick a single-tenant site, ideally in your own ASN)"
                    return 1
                fi
                if reality_dest_is_shared_frontend "$_xsn" 443; then
                    _node_cli_err "warning: server-name ${_xsn} is a shared CDN frontend (probe ${REALITY_DEST_SHARED_BY} got a valid certificate on the same IP); enabling REALITY fallback rate limiting for this node"
                    json=$(printf '%s' "$json" | jq -c '.limit_fallback = true') || return 1
                fi
                private=$(printf '%s' "$json" | jq -r '.private_key // empty')
                public=$(printf '%s' "$json" | jq -r '.public_key // empty')
                if [[ -z "$private" || -z "$public" ]]; then
                    pair=$(_node_cli_keypair xray xhttp) || {
                        _node_cli_err "XHTTP Reality keys are missing and Xray could not generate them"
                        return 1
                    }
                    private=${pair%%$'\t'*}; public=${pair#*$'\t'}
                    json=$(printf '%s' "$json" | jq -c --arg private "$private" --arg public "$public" \
                        '.private_key=$private | .public_key=$public') || return 1
                fi
            fi
            ;;
        ss2022)
            method=$(printf '%s' "$json" | jq -r '.method // "2022-blake3-aes-128-gcm"')
            json=$(printf '%s' "$json" | jq -c --arg method "$method" --arg password "$(_node_cli_ss_password "$method")" '
              .method //= $method | .password //= $password') || return 1
            if [[ "$core" == "xray" ]]; then
                json=$(printf '%s' "$json" | jq -c '.listen //= "0.0.0.0"') || return 1
            else
                json=$(printf '%s' "$json" | jq -c '.listen //= "::"') || return 1
            fi
            ;;
        hysteria2)
            json=$(printf '%s' "$json" | jq -c --arg password "$(rand_str 24)" '
              .password //= $password | .insecure //= 0 | .up //= 0 | .down //= 0 |
              .masquerade //= "https://www.bing.com" | .obfs_pass //= "" | .domain //= ""') || return 1
            ;;
        anytls)
            json=$(printf '%s' "$json" | jq -c --arg password "$(rand_str 20)" '
              .password //= $password | .insecure //= 0 | .domain //= ""') || return 1
            ;;
        tuic)
            json=$(printf '%s' "$json" | jq -c --arg uuid "$(uuid_gen)" --arg password "$(rand_str 24)" '
              .uuid //= $uuid | .password //= $password | .insecure //= 0 | .domain //= "" |
              .congestion_control //= "bbr"') || return 1
            ;;
        wireguard)
            # shellcheck source=/dev/null
            source "$LIB_DIR/singbox/wireguard.sh"
            if [[ -z "$(printf '%s' "$json" | jq -r '.private_key // empty')" ]]; then
                local wkp; wkp=$(sb_wg_keypair) || { _node_cli_err "WireGuard keys need sing-box (sing-box generate wg-keypair)"; return 1; }
                json=$(printf '%s' "$json" | jq -c --arg k "${wkp%%$'\t'*}" --arg p "${wkp#*$'\t'}" '.private_key = $k | .public_key = $p') || return 1
            fi
            [[ -n "$(printf '%s' "$json" | jq -r '.subnet // empty')" ]] \
                || json=$(printf '%s' "$json" | jq -c --arg s "$(_sb_wg_free_net)" '.subnet = $s') || return 1
            json=$(printf '%s' "$json" | jq -c '.mtu //= 1408 | .peers //= []') || return 1
            local wn wi; wn=$(printf '%s' "$json" | jq -r '.peer_count // 1')
            [[ "$wn" =~ ^[0-9]+$ ]] && (( wn >= 1 && wn <= 50 )) || { _node_cli_err "--peer-count must be 1-50"; return 1; }
            for (( wi = $(printf '%s' "$json" | jq '.peers | length'); wi < wn; wi++ )); do
                json=$(sb_wg_new_peer "$json" "peer$((wi + 1))") || { _node_cli_err "could not generate WireGuard peer keys"; return 1; }
            done
            json=$(printf '%s' "$json" | jq -c 'del(.peer_count)') || return 1
            ;;
        snell)
            local snell_default=4
            [[ "$core" == "sing-box" ]] && snell_default=5
            json=$(printf '%s' "$json" | jq -c --arg psk "$(rand_str 24)" --argjson version "$snell_default" '
              .version //= $version | .psk //= $psk | .listen //= "::" |
              .obfs_mode //= "" | .obfs_host //= ""') || return 1
            ;;
    esac

    json=$(_node_cli_vless_enc "$core" "$proto" "$json") || return 1

    # ShadowTLS v3：--shadow-tls-sni <握手目标>（密码缺省随机）。只有 mihomo 的
    # ss2022 / snell listener 带这个能力，且 snell 的 obfs 与它互斥。
    if [[ -n "$(printf '%s' "$json" | jq -r '.stls_sni // empty')" ]]; then
        if [[ "$core" != "mihomo" || ( "$proto" != "ss2022" && "$proto" != "snell" ) ]]; then
            _node_cli_err "--shadow-tls-sni is only available for mihomo ss2022 and snell"; return 1
        fi
        if [[ -n "$(printf '%s' "$json" | jq -r '.obfs_mode // empty')" ]]; then
            _node_cli_err "ShadowTLS and snell obfs are mutually exclusive"; return 1
        fi
        json=$(printf '%s' "$json" | jq -c --arg pw "$(rand_str 24)" '.stls_password //= $pw') || return 1
    fi
    printf '%s' "$json"
}

# VLESS Encryption: vless_enc x25519|mlkem768 has the core make a key pair
# (server decryption / client encryption), none takes them away. sing-box's
# VLESS has no such thing. Keys already there stay — on an update [old node]
# unless they were made for the other kind (vless_enc records which).
_node_cli_vless_enc() {   # <core> <proto> <node json> [old node json]
    local core="$1" proto="$2" json="$3" old="${4:-}" want had _vpair=""
    want=$(printf '%s' "$json" | jq -r '.vless_enc // empty')
    [[ -n "$want" ]] || { printf '%s' "$json"; return 0; }
    if [[ "$want" == none ]]; then
        printf '%s' "$json" | jq -c 'del(.vless_enc, .vless_decryption, .vless_encryption)'
        return 0
    fi
    [[ "$want" == x25519 || "$want" == mlkem768 ]] \
        || { _node_cli_err "--vless-enc must be x25519, mlkem768 or none"; return 1; }
    case "$core/$proto" in
        xray/reality|xray/vision|xray/xhttp|mihomo/vless) ;;
        *) _node_cli_err "--vless-enc is only available for xray reality/vision/xhttp and mihomo vless"; return 1 ;;
    esac
    if [[ -n "$(printf '%s' "$json" | jq -r '.vless_decryption // empty')" ]]; then
        had=""; [[ -n "$old" ]] && had=$(printf '%s' "$old" | jq -r '.vless_enc // empty')
        [[ -z "$had" || "$had" == "$want" ]] && { printf '%s' "$json"; return 0; }
    fi
    case "$core" in
        xray)
            declare -f xray_vlessenc_gen &>/dev/null || source "$LIB_DIR/xray/core.sh"
            _vpair=$(xray_vlessenc_gen "$want") ;;
        mihomo)
            declare -f mh_vlessenc_gen &>/dev/null || source "$LIB_DIR/mihomo/vless.sh"
            _vpair=$(mh_vlessenc_gen "$want") ;;
    esac
    [[ -n "$_vpair" ]] || { _node_cli_err "could not generate VLESS Encryption keys; is a recent $core installed?"; return 1; }
    printf '%s' "$json" | jq -c --arg d "${_vpair%%$'\t'*}" --arg e "${_vpair#*$'\t'}" \
        '.vless_decryption = $d | .vless_encryption = $e'
}

_node_cli_validate() {
    local core="$1" proto="$2" json="$3" context="${4:-update}" mode method
    if ! printf '%s' "$json" | jq -e '
        type == "object" and
        (.tag | type == "string" and length > 0 and length <= 128) and
        (.port | type == "number" and floor == . and . >= 1 and . <= 65535)' >/dev/null; then
        _node_cli_err "node requires a non-empty tag and an integer port in 1..65535"
        return 1
    fi
    if ! printf '%s' "$json" | jq -e --arg proto "$proto" --arg core "$core" '
      if $proto == "reality" then
        ([.uuid,.private_key,.public_key,.server_name,.dest,.flow] | all(type == "string" and length > 0)) and
        (.short_ids | type == "array" and length > 0)
      elif $proto == "vision" then
        ([.uuid,.domain,.flow,.listen_addr] | all(type == "string" and length > 0)) and
        (.public_port | type == "number") and (.fallback_enabled | type == "boolean")
      elif $proto == "xhttp" then
        ([.uuid,.mode,.path,.listen_addr] | all(type == "string" and length > 0)) and
        (.public_port | type == "number") and (.fallback_enabled | type == "boolean") and
        (if .mode == "reality-layer" then
           ([.private_key,.public_key,.short_id,.server_name] | all(type == "string" and length > 0))
         elif .mode == "mkcp" then
           # mKCP 不套 TLS，没有域名和证书；seed 是它唯一的加密材料，不能为空
           (.kcp_seed | type == "string" and length > 0)
         else (.domain | type == "string" and length > 0) end)
      elif $proto == "vless" then
        ([.uuid,.transport,.sni,.cert_path,.key_path,.listen_addr] | all(type == "string" and length > 0)) and
        (.public_port | type == "number") and
        # 传输能力按内核区分：sing-box 有 quic 没有 xhttp，mihomo 反过来
        # 先把 .transport 取出来再进管道：写成 [...] | index(.transport) 时
        # 管道里的 . 已经是那个数组，.transport 就成了「用字符串索引数组」，
        # jq 报 Cannot index array with string 并让整条校验失败。
        (.transport as $tr |
         if $core == "mihomo"
         then (["tcp","ws","grpc","xhttp"] | index($tr)) != null
         else (["tcp","ws","grpc","http","httpupgrade","quic"] | index($tr)) != null end)
      elif $proto == "socks" then
        (.listen_addr | type == "string" and length > 0) and
        (.public_port | type == "number") and
        ([.username,.password] | all(type == "string")) and
        # 公网监听必须有凭据；仅本机可以免认证
        (if .listen_addr == "127.0.0.1" then true
         else (.username | length > 0) and (.password | length > 0) end)
      elif $proto == "vmess" then
        # VMess 固定 WS+TLS：uuid 和 path 两者缺一不可
        ([.uuid,.path,.listen_addr] | all(type == "string" and length > 0)) and
        (.public_port | type == "number") and
        (if $core == "xray" then (.domain | type == "string" and length > 0)
         else ([.sni,.cert_path,.key_path] | all(type == "string" and length > 0)) end)
      elif $proto == "trojan" then
        # Xray 侧强制真实域名+证书，走 Nginx 伪装站回落；sing-box / mihomo 侧
        # 允许自签名证书（与 anytls 同构），两者的节点字段并不相同。
        (if $core == "xray" then
           ([.password,.domain,.listen_addr] | all(type == "string" and length > 0)) and
           (.public_port | type == "number") and (.fallback_enabled | type == "boolean")
         else
           ([.password,.sni,.cert_path,.key_path] | all(type == "string" and length > 0)) and
           (.insecure | type == "number" or type == "boolean")
         end)
      elif $proto == "ss2022" then
        ([.method,.password,.listen] | all(type == "string" and length > 0))
      elif $proto == "hysteria2" then
        ([.password,.sni,.cert_path,.key_path] | all(type == "string" and length > 0)) and
        (.insecure | type == "number" or type == "boolean") and
        # QUIC 混淆类型：未设置 = salamander（老节点）；gecko 需 sing-box 1.14+ / mihomo 1.19.26+
        ((.obfs_type // "salamander") as $o | ["salamander","gecko"] | index($o)) != null and
        # BBR 配置档：未设置 = 内核默认（standard）
        ((.bbr_profile // "") as $b | ["","conservative","standard","aggressive"] | index($b)) != null and
        # 关闭路径 MTU 探测：未设置 = 内核默认（探测）
        ((.disable_pmtud // false) | type == "boolean")
      elif $proto == "anytls" then
        ([.password,.sni,.cert_path,.key_path] | all(type == "string" and length > 0)) and
        (.insecure | type == "number" or type == "boolean")
      elif $proto == "wireguard" then
        ([.private_key,.public_key,.subnet] | all(type == "string" and length > 0)) and
        (.peers | type == "array" and length > 0 and
          all(.[]; ([.public_key,.private_key] | all(type == "string" and length > 0)) and (.host | type == "number")))
      elif $proto == "tuic" then
        ([.uuid,.password,.sni,.cert_path,.key_path] | all(type == "string" and length > 0)) and
        (.insecure | type == "number" or type == "boolean") and
        ((.congestion_control // "bbr") as $c | ["bbr","cubic","new_reno"] | index($c)) != null
      elif $proto == "snell" then
        ([.psk,.listen] | all(type == "string" and length > 0)) and
        (.version | type == "number")
      else false end' >/dev/null; then
        _node_cli_err "node does not satisfy the $core/$proto schema; use --help for input options"
        return 1
    fi
    case "$proto" in
        hysteria2)
            # Xray 的 salamander 要求 PSK ≥4 字节，否则整个 Xray 起不来；三个核心统一收这个下限
            if ! printf '%s' "$json" | jq -e '(.obfs_pass // "") | length == 0 or length >= 4' >/dev/null; then
                _node_cli_err "--obfs-pass must be at least 4 characters"; return 1
            fi
            local _hop; _hop=$(printf '%s' "$json" | jq -r '.hop_ports // ""')
            if [[ -n "$_hop" ]]; then
                # shellcheck source=/dev/null
                source "$LIB_DIR/hop.sh"
                if ! hop_range_valid "$_hop" "$(printf '%s' "$json" | jq -r '.port')" "$(printf '%s' "$json" | jq -r '.tag')"; then
                    _node_cli_err "--hop-ports $_hop is not usable ($HOP_ERR): 1024-65535, at most $HOP_MAX_SPAN ports, no other node or UDP listener inside"
                    return 1
                fi
            fi
            ;;
        ss2022)
            method=$(printf '%s' "$json" | jq -r '.method')
            case "$method" in
                2022-blake3-aes-128-gcm|2022-blake3-aes-256-gcm|2022-blake3-chacha20-poly1305) ;;
                *) _node_cli_err "unsupported SS2022 method: $method"; return 1 ;;
            esac
            ;;
        snell)
            if ! printf '%s' "$json" | jq -e --arg core "$core" '
              if $core == "sing-box" then (.version == 5 or .version == 6)
              else (.version == 4 or .version == 5) end' >/dev/null; then
                _node_cli_err "unsupported Snell version for $core"
                return 1
            fi
            ;;
        xhttp)
            mode=$(printf '%s' "$json" | jq -r '.mode')
            case "$mode" in xhttp|upgrade|ws|grpc|reality-layer|httpupgrade|h2|mkcp) ;; *) _node_cli_err "unsupported XHTTP mode: $mode"; return 1 ;; esac
            ;;
    esac
    _node_cli_exit_check "$json" || return 1
    # A loopback listener for a 443-capable pair only makes sense behind the
    # shared SNI map, which --mount-443 sets up (see _node_cli_mount_apply).
    if [[ "$context" == "add" ]] && _node_cli_fronted_pair "$core" "$proto" \
        && [[ "${_NODE_CLI_MOUNT443:-0}" != "1" ]] \
        && [[ "$(printf '%s' "$json" | jq -r '.listen_addr // ""')" == "127.0.0.1" ]]; then
        _node_cli_err "a loopback $core/$proto node is only reachable through the shared 443; pass --mount-443 instead of --listen-addr 127.0.0.1"
        return 1
    fi
    return 0
}

_node_cli_validate_update_side_effects() {
    local core="$1" proto="$2" old="$3" new="$4"
    _node_cli_fronted_pair "$core" "$proto" || return 0
    # Port and SNI changes on a mounted node are carried into the SNI map after
    # the apply (_node_cli_cmd_update). Moving a node between direct listening
    # and the shared 443 changes its public address, so that is delete + add.
    if ! jq -en --argjson old "$old" --argjson new "$new" \
        '($old.listen_addr // "") == ($new.listen_addr // "")' >/dev/null; then
        _node_cli_err "moving a $core node between direct listening and the shared 443 is not an update; delete it and add it again (with or without --mount-443)"
        return 1
    fi
}

_node_cli_check_port_conflict() {
    local core="$1" proto="$2" tag="$3" port="$4" all conflict transport
    transport=$(_node_cli_transport "$proto")
    # Listener ports are machine-wide, not core-local. TCP and UDP namespaces
    # are independent, however, so Reality:443/tcp may coexist with HY2:443/udp.
    all=$(_node_cli_collect "" "") || return 1
    conflict=$(printf '%s' "$all" | jq -r \
      --arg core "$core" --arg proto "$proto" --arg tag "$tag" \
      --arg transport "$transport" --argjson port "$port" '
      def transport: if (.protocol == "hysteria2" or .protocol == "tuic" or .protocol == "wireguard") then "udp" else "tcp" end;
      first(.[] | select(
        .port == $port and transport == $transport and
        ((.core != $core) or (.protocol != $proto) or (.tag != $tag))
      ) | .id) // empty')
    if [[ -n "$conflict" ]]; then
        _node_cli_err "port $port is already used by $conflict"
        return 1
    fi
}

_node_cli_transport() {
    case "$1" in hysteria2|tuic|wireguard) printf udp ;; *) printf tcp ;; esac
}

# The L4 a node takes clients on, as the firewall sees it: tcp, udp or both.
_node_cli_fw_l4() {   # <proto> <node json>
    local n="$2"
    case "$1" in
        hysteria2|tuic|wireguard) printf udp ;;
        ss2022|snell) printf both ;;
        socks) [[ "$(printf '%s' "$n" | jq -r '.udp // true')" == true ]] && printf both || printf tcp ;;
        xhttp) [[ "$(printf '%s' "$n" | jq -r '.mode // ""')" == mkcp ]] && printf udp || printf tcp ;;
        vless) [[ "$(printf '%s' "$n" | jq -r '.transport // "tcp"')" == quic ]] && printf udp || printf tcp ;;
        *) printf tcp ;;
    esac
}

# Clients have to get through the server's firewall. The menus ask before they
# open a node's port; here nobody can be asked (the PSM panel adds its nodes
# through this), so the port is opened as the node is made. A rule PSM had to
# add is written down in $CFG_DIR/firewall-ports, and deleting the last node on
# that port takes it out again; a port the firewall already let in is left as it was.
_NODE_CLI_FW_LEDGER="$CFG_DIR/firewall-ports"

_node_cli_fw_open() {   # <proto> <node json>
    local proto="$1" n="$2" port l4 p
    [[ "$(printf '%s' "$n" | jq -r '.listen_addr // .listen // ""')" == "127.0.0.1" ]] && return 0
    declare -f firewall_backend &>/dev/null || source "$LIB_DIR/system.sh"
    [[ -n "$(firewall_backend)" ]] || return 0
    port=$(printf '%s' "$n" | jq -r '.port'); l4=$(_node_cli_fw_l4 "$proto" "$n")
    for p in tcp udp; do
        [[ "$l4" == both || "$l4" == "$p" ]] || continue
        grep -qx "$port/$p" "$_NODE_CLI_FW_LEDGER" 2>/dev/null && continue
        firewall_port_allowed "$port" "$p" && continue
        if firewall_open_port "$port" "$p" >&2; then
            mkdir -p "$CFG_DIR" && printf '%s/%s\n' "$port" "$p" >> "$_NODE_CLI_FW_LEDGER"
        else
            _node_cli_err "warning: could not open $p/$port in the firewall; clients cannot reach the node until it is open"
        fi
    done
    return 0
}

_node_cli_fw_close() {   # <node json>, once it has left its store
    local n="$1" port p others
    [[ -s "$_NODE_CLI_FW_LEDGER" ]] || return 0
    port=$(printf '%s' "$n" | jq -r '.port')
    grep -q "^$port/" "$_NODE_CLI_FW_LEDGER" || return 0
    # another node on the port (on either L4) keeps it open
    others=$(_node_cli_collect "" "" 2>/dev/null | jq --argjson p "$port" '[.[] | select(.port == $p)] | length' 2>/dev/null)
    [[ "$others" == 0 ]] || return 0
    declare -f firewall_close_port &>/dev/null || source "$LIB_DIR/system.sh"
    for p in tcp udp; do
        grep -qx "$port/$p" "$_NODE_CLI_FW_LEDGER" || continue
        firewall_close_port "$port" "$p"
        sed -i "\|^$port/$p\$|d" "$_NODE_CLI_FW_LEDGER"
    done
    return 0
}

# sing-box / mihomo TLS nodes (and Xray's Hysteria2) made without certificate
# files: the SNI's own certificate when PSM has one ($NGINX_SSL_DIR/<domain>/,
# from the certificate menu), else a self-signed one made here, with
# insecure = 1 so the node's links tell clients to accept it. The menus do the
# same (_sb_resolve_tls / _mh_resolve_tls); before this such a node could only
# be made where certificate files already were, so on a fresh server from the
# panel it failed.
_node_cli_tls_auto() {   # <core> <proto> <node json> → node json
    local core="$1" proto="$2" n="$3" cp kp sni dom dir name crt key
    case "$core/$proto" in
        sing-box/hysteria2|sing-box/tuic|sing-box/anytls|sing-box/vless|sing-box/trojan|sing-box/vmess)
            dir="$SINGBOX_CFG_DIR/certs" ;;
        mihomo/hysteria2|mihomo/tuic|mihomo/anytls|mihomo/vless|mihomo/trojan|mihomo/vmess)
            dir="$MIHOMO_CFG_DIR/certs" ;;
        xray/hysteria2) dir="$CFG_DIR/xray/certs" ;;
        *) printf '%s' "$n"; return 0 ;;
    esac
    cp=$(printf '%s' "$n" | jq -r '.cert_path // ""'); kp=$(printf '%s' "$n" | jq -r '.key_path // ""')
    if [[ -n "$cp" || -n "$kp" ]]; then
        if [[ ! -s "$cp" || ! -s "$kp" ]]; then
            _node_cli_err "certificate files not found: cert_path=${cp:-<none>} key_path=${kp:-<none>} (leave both out for a self-signed certificate)"
            return 1
        fi
        printf '%s' "$n"; return 0
    fi
    sni=$(printf '%s' "$n" | jq -r '.sni // ""'); dom=$(printf '%s' "$n" | jq -r '.domain // ""')
    [[ -n "$dom" ]] || dom="$sni"
    if [[ -n "$dom" && -s "$NGINX_SSL_DIR/$dom/fullchain.pem" && -s "$NGINX_SSL_DIR/$dom/privkey.pem" ]]; then
        printf '%s' "$n" | jq -c --arg c "$NGINX_SSL_DIR/$dom/fullchain.pem" --arg k "$NGINX_SSL_DIR/$dom/privkey.pem" \
            --arg s "$dom" '.cert_path = $c | .key_path = $k | .sni = $s | .insecure = 0'
        return
    fi
    [[ -n "$sni" ]] || sni="www.bing.com"
    name=$(printf '%s' "$n" | jq -r '.tag' | tr -c 'A-Za-z0-9._\n-' '_')
    crt="$dir/$name.crt"; key="$dir/$name.key"
    if [[ ! -s "$key" ]] || ! openssl x509 -in "$crt" -noout -subject 2>/dev/null | grep -q "CN *= *${sni}\$"; then
        mkdir -p "$dir"
        openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -days 3650 \
            -subj "/CN=$sni" -addext "subjectAltName=DNS:$sni" -keyout "$key" -out "$crt" >/dev/null 2>&1 \
            || { _node_cli_err "could not make a self-signed certificate in $dir"; return 1; }
        chmod 600 "$key"
    fi
    printf '%s' "$n" | jq -c --arg c "$crt" --arg k "$key" --arg s "$sni" \
        '.cert_path = $c | .key_path = $k | .sni = $s | .insecure = 1'
}

# A node's exit (the PSM panel's 出口分流, lib/exit_cli.sh): .exit warp|vpngate
# (none / empty: no exit), .exit_sites all|ai|streaming|geosite names,
# .exit_country the residential tunnel's country the first time it is made.
_node_cli_exit_of() { printf '%s' "$1" | jq -r '(.exit // "") | if . == "none" then "" else . end'; }

_node_cli_exit_check() {   # <node json>
    local n="$1" ex cc
    ex=$(_node_cli_exit_of "$n")
    case "$ex" in "") return 0 ;; warp|vpngate) ;; *) _node_cli_err "exit must be warp, vpngate or none"; return 1 ;; esac
    source "$LIB_DIR/exit_cli.sh"
    exit_sites_geosite "$(printf '%s' "$n" | jq -r '.exit_sites // "all"')" >/dev/null || return 1
    cc=$(printf '%s' "$n" | jq -r '.exit_country // ""')
    [[ -z "$cc" || "$cc" =~ ^[A-Z]{2}$ ]] || { _node_cli_err "exit_country must be a two-letter code (JP, KR, US …)"; return 1; }
}

_node_cli_exit_prepare() {   # <core> <node json>: its exit's outbound, before the node is made
    local ex; ex=$(_node_cli_exit_of "$2")
    [[ -n "$ex" ]] || return 0
    source "$LIB_DIR/exit_cli.sh"
    exit_ensure "$1" "$ex" "$(printf '%s' "$2" | jq -r '.exit_country // ""')"
}

_node_cli_exit_rules() {   # <core> <tag> <node json>: its exit rule (or none), once it is made
    local ex; ex=$(_node_cli_exit_of "$3")
    source "$LIB_DIR/exit_cli.sh"
    [[ -n "$ex" ]] || exit_node_has "$1" "$2" || return 0
    exit_node_set "$1" "$2" "$ex" "$(printf '%s' "$3" | jq -r '.exit_sites // "all"')"
}

# Hysteria2 --bbr-profile: how hard the server's BBR congestion control pushes
# (conservative / standard / aggressive, from Hysteria 2.8), new this year in
# all three cores. An older core refuses the field (sing-box) or ignores it
# without a word (Xray, mihomo), so the version that has it is asked for.
_node_cli_bbr_check() {   # <core> <proto> <node json>
    local core="$1" want min cur=""
    [[ "$2" == hysteria2 ]] || return 0
    want=$(printf '%s' "$3" | jq -r '.bbr_profile // ""')
    [[ -n "$want" ]] || return 0
    case "$core" in
        sing-box) min=1.14.0;  [[ -x "$SINGBOX_BIN" ]] && cur=$("$SINGBOX_BIN" version 2>/dev/null | awk 'NR==1 {print $3}') ;;
        mihomo)   min=1.19.24; [[ -x "$MIHOMO_BIN" ]] && cur=$("$MIHOMO_BIN" -v 2>/dev/null | grep -oE 'v[0-9]+\.[0-9]+\.[0-9]+' | head -1) ;;
        xray)     min=26.4.13; [[ -x "$XRAY_BIN" ]] && cur=$("$XRAY_BIN" version 2>/dev/null | awk 'NR==1 {print $2}') ;;
        *) return 0 ;;
    esac
    cur=${cur#v}; cur=${cur%%-*}
    [[ "$cur" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || return 0   # no core yet, or an alpha build: newest anyway
    [[ "$(printf '%s\n%s\n' "$min" "$cur" | sort -V | head -1)" == "$min" ]] && return 0
    _node_cli_err "--bbr-profile needs $core $min or newer (installed: $cur); upgrade the core first"
    return 1
}

# Hysteria2 --disable-pmtud (#7): sing-box has the QUIC field from 1.14 (an older
# one refuses the whole config), every Xray with Hysteria2 has quicParams'
# disablePathMTUDiscovery, and mihomo has no such option at all.
_node_cli_pmtud_check() {   # <core> <proto> <node json>
    local cur=""
    [[ "$2" == hysteria2 ]] || return 0
    [[ "$(printf '%s' "$3" | jq -r '.disable_pmtud // false')" == true ]] || return 0
    case "$1" in
        mihomo)
            _node_cli_err "--disable-pmtud: mihomo's Hysteria2 has no such option; use sing-box (1.14+) or Xray"
            return 1 ;;
        sing-box)
            [[ -x "$SINGBOX_BIN" ]] && cur=$("$SINGBOX_BIN" version 2>/dev/null | awk 'NR==1 {print $3}')
            cur=${cur%%-*}
            [[ "$cur" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || return 0
            [[ "$(printf '%s\n%s\n' 1.14.0 "$cur" | sort -V | head -1)" == 1.14.0 ]] && return 0
            _node_cli_err "--disable-pmtud needs sing-box 1.14.0 or newer (installed: $cur); upgrade the core first"
            return 1 ;;
    esac
    return 0
}

# Xray's TLS protocols with a domain (Vision, XHTTP over TLS, Trojan, VMess)
# use that domain's certificate from the certificate menu. Without it Xray
# would refuse its whole config and every node on it would go down, so the
# node is refused here, saying what to do.
_node_cli_xray_cert_check() {   # <core> <proto> <node json>
    local core="$1" proto="$2" n="$3" dom
    [[ "$core" == xray ]] || return 0
    case "$proto" in
        vision|trojan|vmess) ;;
        xhttp) case "$(printf '%s' "$n" | jq -r '.mode // ""')" in mkcp|reality-layer) return 0 ;; esac ;;
        *) return 0 ;;
    esac
    dom=$(printf '%s' "$n" | jq -r '.domain // ""')
    [[ -n "$dom" ]] || return 0   # _node_cli_validate says what is missing
    [[ -s "$NGINX_SSL_DIR/$dom/fullchain.pem" && -s "$NGINX_SSL_DIR/$dom/privkey.pem" ]] && return 0
    _node_cli_err "no certificate for $dom: Xray $proto needs $NGINX_SSL_DIR/$dom/fullchain.pem and privkey.pem. Issue it first (psm menu → SSL certificates), or use REALITY, or sing-box / mihomo, which make a self-signed certificate"
    return 1
}

# Core/protocol pairs that support Nginx 443 SNI fronting (listen_addr
# 127.0.0.1 + shared SNI map): add --mount-443, and update/delete keep the
# map in step (_node_cli_mount_precheck / _mount_apply / _mount_remove).
_node_cli_fronted_pair() {
    case "$1/$2" in
        xray/reality|xray/vision|xray/xhttp|xray/trojan|xray/vmess) return 0 ;;
        sing-box/reality|sing-box/anytls|sing-box/trojan|sing-box/vmess|sing-box/vless) return 0 ;;
        mihomo/reality|mihomo/anytls|mihomo/trojan|mihomo/vmess|mihomo/vless) return 0 ;;
        *) return 1 ;;
    esac
}

_node_cli_port_is_listening() {
    local port="$1" transport="$2"
    if command -v ss >/dev/null 2>&1; then
        if [[ "$transport" == "udp" ]]; then
            ss -lun 2>/dev/null | awk '{print $4}' | grep -qE "[:.]${port}$"
        else
            ss -ltn 2>/dev/null | awk '{print $4}' | grep -qE "[:.]${port}$"
        fi
        return
    fi
    if command -v netstat >/dev/null 2>&1; then
        if [[ "$transport" == "udp" ]]; then
            netstat -anu 2>/dev/null | awk '{print $4}' | grep -qE "[:.]${port}$"
        else
            netstat -ant 2>/dev/null | awk '$6 == "LISTEN" {print $4}' | grep -qE "[:.]${port}$"
        fi
        return
    fi
    return 1
}

# --ech true|false on the sing-box/mihomo TLS pairs: generate the ECH key pair
# (with whichever core is installed) or drop it. The store keeps only ech_key /
# ech_config; the builders merge them (lib/common.sh _sb_ech_merge/_mh_ech_merge).
_node_cli_ech() {   # <core> <proto> <node-json> → node JSON
    local core="$1" proto="$2" n="$3" want name
    want=$(printf '%s' "$n" | jq -r 'if has("ech") then (.ech | tostring) else "" end')
    if [[ -z "$want" ]]; then printf '%s' "$n"; return 0; fi
    case "$core/$proto" in
        sing-box/vless|sing-box/trojan|sing-box/anytls|sing-box/hysteria2|sing-box/tuic) ;;
        mihomo/vless|mihomo/trojan|mihomo/anytls|mihomo/hysteria2|mihomo/tuic) ;;
        *) _node_cli_err "--ech is available for sing-box/mihomo vless, trojan, anytls, hysteria2 and tuic"; return 1 ;;
    esac
    case "$want" in
        true|1)
            if [[ -z "$(printf '%s' "$n" | jq -r '.ech_key // empty')" ]]; then
                name=$(printf '%s' "$n" | jq -r '.sni // .domain // empty')
                psm_ech_keypair "${name:-www.bing.com}" || { _node_cli_err "could not generate ECH keys (needs sing-box or mihomo)"; return 1; }
                n=$(printf '%s' "$n" | jq -c --arg k "$ECH_KEY_PEM" --arg c "$ECH_CONFIG_B64" '.ech_key = $k | .ech_config = $c')
            fi
            printf '%s' "$n" | jq -c 'del(.ech)' ;;
        false|0) printf '%s' "$n" | jq -c 'del(.ech, .ech_key, .ech_config)' ;;
        *) _node_cli_err "--ech takes true or false"; return 1 ;;
    esac
}

# The SNI that routes a node through the shared 443 map: the same key the
# interactive flows write with _sni_add_entry <key> 127.0.0.1:<port>.
_node_cli_sni_key() {   # <proto> <node-json>
    printf '%s' "$2" | jq -r --arg p "$1" '
      if $p == "reality" then (.server_name // "")
      elif ($p == "xhttp" or $p == "vision" or $p == "trojan" or $p == "vmess")
        then (if (.domain // "") != "" then .domain else (.server_name // .sni // "") end)
      else (.sni // .domain // "") end'
}

_node_cli_is_mounted() {   # <core> <proto> <node-json>
    _node_cli_fronted_pair "$1" "$2" \
        && printf '%s' "$3" | jq -e '.listen_addr == "127.0.0.1"' >/dev/null 2>&1
}

# Before a node is committed: Nginx with the stream SNI map must exist (it is
# installed when missing) and <key> must not already route to another backend.
# [own-port] is the node's current loopback port on update/replace: the entry
# still points there until the change is applied, and that is not a conflict.
_node_cli_mount_precheck() {   # <key> <port> [own-port]
    local key="$1" port="$2" own="${3:-}" cur
    # shellcheck source=/dev/null
    source "$LIB_DIR/nginx.sh" || return 1
    if ! is_installed nginx || [[ ! -f "$(_sni_map_file)" ]]; then
        nginx_ensure_stream_sni </dev/null >&2 || { _node_cli_err "could not set up Nginx for the shared 443"; return 1; }
    fi
    if cur=$(_sni_lookup_entry "$key") && [[ "$cur" != "127.0.0.1:${port}" ]] \
        && [[ -z "$own" || "$cur" != "127.0.0.1:${own}" ]]; then
        _node_cli_err "SNI $key already routes to $cur on the shared 443"
        return 1
    fi
}

# Write the route and prove Nginx accepted it; _sni_add_entry itself reports
# success even when the reload failed. A rejected route is taken out again.
_node_cli_mount_apply() {   # <key> <port>
    _sni_add_entry "$1" "127.0.0.1:$2" >&2 || return 1
    if ! nginx -t >/dev/null 2>&1; then
        _sni_remove_entry "$1" >&2 || true
        return 1
    fi
}

# Drop <key> from the map, but only while it still routes to this node's port.
_node_cli_mount_remove() {   # <key> <port>
    local cur
    # shellcheck source=/dev/null
    source "$LIB_DIR/nginx.sh" || return 0
    cur=$(_sni_lookup_entry "$1") || return 0
    [[ "$cur" == "127.0.0.1:$2" ]] && _sni_remove_entry "$1" >&2
    return 0
}

# Real handshake through the core before a REALITY target is accepted (see
# reality_probe_core). Skipped with --skip-dest-probe and when the target did
# not change; a machine that cannot run the probe (no core, no curl) passes.
_node_cli_probe_reality() {   # <core> <proto> <node> [old-node]
    local core="$1" proto="$2" node="$3" old="${4:-}" pc sn dest
    [[ "${_NODE_CLI_SKIP_PROBE:-0}" == "1" ]] && return 0
    case "$proto" in
        reality) pc="$core" ;;
        xhttp) [[ "$(printf '%s' "$node" | jq -r '.mode')" == "reality-layer" ]] || return 0; pc=xray ;;
        *) return 0 ;;
    esac
    sn=$(printf '%s' "$node" | jq -r '.server_name // empty')
    [[ -n "$sn" ]] || return 0
    dest=$(printf '%s' "$node" | jq -r --arg sn "$sn" '.dest // ($sn + ":443")')
    reality_dest_is_local "$dest" && return 0
    if [[ -n "$old" ]] && jq -en --argjson a "$old" --argjson b "$node" \
        '[$a.server_name, $a.dest] == [$b.server_name, $b.dest]' >/dev/null 2>&1; then
        return 0
    fi
    reality_probe_core "$pc" "$dest" "$sn"
    case $? in
        0) return 0 ;;
        2) _node_cli_err "note: REALITY target not probed (${REALITY_PROBE_REASON})"; return 0 ;;
    esac
    _node_cli_err "$pc cannot complete a REALITY handshake with $sn ($dest) as the target: the node would install, but no client could connect. Pick another --server-name/--dest, or pass --skip-dest-probe"
    return 1
}

_node_cli_restart_old_cfg() {
    case "$1" in
        xray) xray_test_restart >&2 || true ;;
        sing-box) sb_test_restart >&2 || true ;;
        mihomo) mh_test_restart >&2 || true ;;
    esac
}

_node_cli_commit_store() {
    local core="$1" proto="$2" new_store="$3" store_only="$4"
    local path module apply live bin old_store existed=0 live_backup="" ok=0
    path=$(_node_cli_store_path "$core" "$proto")
    old_store=$(_node_cli_read_store "$path") || return 1
    [[ -f "$path" ]] && existed=1

    if [[ "$store_only" != "1" ]]; then
        module=$(_node_cli_module_path "$core" "$proto")
        apply=$(_node_cli_apply_fn "$core" "$proto") || return 1
        live=$(_node_cli_live_cfg "$core")
        bin=$(_node_cli_core_bin "$core")
        [[ -x "$bin" ]] || { _node_cli_err "$core is not installed: $bin"; return 1; }
        [[ -f "$live" ]] || { _node_cli_err "$core config does not exist: $live"; return 1; }
        live_backup=$(mktemp) || return 1
        cp -a "$live" "$live_backup" || { rm -f "$live_backup"; return 1; }
        # shellcheck source=/dev/null
        source "$module"
    fi

    if ! _node_cli_atomic_write "$path" "$new_store"; then
        _node_cli_err "failed to write node store: $path"
        [[ -n "$live_backup" ]] && rm -f "$live_backup"
        return 1
    fi

    if [[ "$store_only" == "1" ]]; then return 0; fi
    if "$apply" >&2; then
        ok=1
    else
        _node_cli_err "apply failed; restoring node store and live config"
        if (( existed )); then _node_cli_atomic_write "$path" "$old_store" || true
        else rm -f "$path"
        fi
        cp -a "$live_backup" "$live" 2>/dev/null || true
        _node_cli_restart_old_cfg "$core"
    fi
    rm -f "$live_backup"
    (( ok == 1 ))
}

