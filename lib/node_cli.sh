_node_cli_err() { printf 'psm node: %s\n' "$*" >&2; }

_node_cli_usage() {
    cat <<'EOF'
Usage:
  psm node list [--core CORE] [--protocol PROTO] [--json] [--show-secrets]
  psm node show CORE PROTO TAG [--json] [--show-secrets]
  psm node add CORE PROTO [--tag TAG] [--port PORT]
               [--input FILE|- | --data JSON|@FILE] [--set KEY=VALUE ...]
               [--set-json KEY=JSON ...] [--replace] [--store-only] [--json]
  psm node update CORE PROTO TAG
               [--input FILE|- | --data JSON|@FILE] [--set KEY=VALUE ...]
               [--set-json KEY=JSON ...] [--unset KEY ...] [--store-only] [--json]
  psm node delete CORE PROTO TAG --yes
               [--if-exists] [--store-only] [--json]
  psm node export CORE PROTO TAG
               [--server HOST] [--format uri|json|surge|singbox|clash]

Cores: xray, sing-box (alias: singbox), mihomo
Protocols:
  xray:     reality, vision, xhttp, ss2022, trojan, vmess, socks, hysteria2 (Xray v26.3.27+)
  sing-box: reality, ss2022, hysteria2, anytls, snell, trojan, vmess, socks, vless, tuic, wireguard
  mihomo:   reality, ss2022, hysteria2, anytls, snell, trojan, vmess, socks, vless, tuic

Protocol inputs:
  reality:   --port; UUID/keys/short ID/SNI/dest receive safe defaults
  vision:    --port --domain
  xhttp:     --port --domain [--mode xhttp|upgrade|ws|grpc|httpupgrade|h2]
             --mode mkcp needs no domain (UDP, no TLS); --kcp-seed / --kcp-header
             --mode reality-layer takes --reality-transport xhttp|grpc
             (--mode h2 is carried by XHTTP stream-one: Xray removed the HTTP transport)
  ShadowTLS v3: --shadow-tls-sni HOST [--shadow-tls-password ...] on mihomo ss2022
             and snell (handshake relayed to HOST:443; not with snell obfs)
  VLESS Encryption (post-quantum): --vless-enc x25519|mlkem768|none on xray reality /
             vision / xhttp and mihomo vless; keys are generated by the core
             (x25519 = short links; mlkem768 = PQ authentication, ~1.6 KB link).
             xhttp --mode mkcp has it by default (x25519): Xray v26.7.7+ clients
             refuse VLESS without TLS; --vless-enc none for older clients only
  trojan:    --port --domain [--password ...]
  vmess:     --port --domain [--uuid ...] [--path ...]   (WS+TLS)
  vless:     --port [--sni ...] [--cert-path ... --key-path ...] [--uuid ...] [--transport ...] [--path ...]
             transport: sing-box tcp|ws|grpc|http|httpupgrade|quic; mihomo tcp|ws|grpc|xhttp
  socks:     --port [--listen-addr 127.0.0.1|0.0.0.0] [--username ...] [--password ...]
             (alias: socks5; loopback by default, public listeners require credentials)
  ss2022:    --port [--method ...] [--password ...]
  hysteria2: --port [--sni ...] [--cert-path ... --key-path ...] [--password ...]
             [--obfs-pass ... [--obfs-type salamander|gecko]]
             [--hop-ports START-END]  port hopping: a UDP range redirected to --port
             [--bbr-profile conservative|standard|aggressive]  how hard the server's
             BBR pushes (unset: the core's default, standard); sing-box 1.14+ /
             mihomo 1.19.24+ / Xray v26.4.13+
             [--disable-pmtud true|false]  switch off QUIC path MTU discovery: keep
             to small packets on paths that drop large ones; sing-box 1.14+ / Xray
             (mihomo has no such option)
             gecko needs sing-box 1.14+ / mihomo 1.19.26+ / Xray v26.3.27+
  anytls:    --port [--sni ...] [--cert-path ... --key-path ...] [--password ...]
  tuic:      --port [--sni ...] [--cert-path ... --key-path ...] [--uuid ...] [--password ...]
             [--congestion-control bbr|cubic|new_reno]   (TUIC v5, UDP)
  wireguard: --port [--peer-count N]   (sing-box; export prints a wg-quick file per client)
  snell:     --port [--version 5|6 for sing-box; 4|5 for mihomo] [--psk ...]

TLS without --cert-path/--key-path (sing-box/mihomo, and Xray's Hysteria2): the
SNI's certificate from /etc/nginx/ssl/<sni>/ when PSM has one, else a
self-signed one (SNI www.bing.com unless given) and insecure=1 in the links.
The node's port is opened in an enforcing ufw / firewalld / iptables, and
closed again with the last node on it.

Exits (Xray, sing-box, mihomo): what comes in on this node leaves through
Cloudflare WARP or the free residential line (VPNGate); the rest goes direct.
  --exit warp|vpngate|none
  --exit-sites all|ai|streaming|GEOSITE,...   (default all)
  --exit-country CC                           the residential line's country the first time (default JP)

Common field options are accepted directly, for example --uuid, --password,
--method, --listen, --listen-addr, --domain, --sni, --cert-path and --key-path.
Use --set for future/protocol-specific fields. Values for numeric, boolean and
array fields are typed automatically; --set-json is always interpreted as JSON.

Shared 443 (Nginx SNI routing), for xray reality/vision/xhttp/trojan/vmess and
sing-box/mihomo reality/anytls/trojan/vmess/vless:
  --mount-443        listen on 127.0.0.1:PORT and route the node's SNI from the
                     public 443 (Nginx is installed when missing). update keeps
                     the route in step with --port / SNI changes, delete removes it.

REALITY targets are tested with a real handshake through the node's core before
the node is created (a target can pass every TLS check and still not work with
REALITY). --skip-dest-probe skips that test.

Queries redact credentials by default. Use --show-secrets only in a protected
terminal or pipeline. Export intentionally includes the credentials required by
clients. --store-only skips core validation/restart and is intended for offline
provisioning and tests.

Selector flags remain supported for scripting compatibility, for example:
  psm node show TAG --core CORE --protocol PROTO --json
EOF
}

