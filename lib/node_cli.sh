_node_cli_result() {
    local status="$1" envelope="$2" as_json="$3" show_secrets="$4"
    if [[ "$as_json" == "1" ]]; then
        printf '%s' "$envelope" | _node_cli_maybe_redact "$show_secrets" | \
            jq -c --arg status "$status" --argjson version "$_NODE_CLI_VERSION" \
            '{status:$status, api_version:$version, item:.}'
    else
        printf '%s: %s\n' "$status" "$(printf '%s' "$envelope" | jq -r '.id')"
    fi
}

_node_cli_require_root_unless_store_only() {
    local state="$1"
    [[ "$(printf '%s' "$state" | jq -r '.store_only')" == "true" ]] && return 0
    if (( EUID != 0 )); then
        _node_cli_err 'applying node changes requires root; use --store-only only for offline provisioning/tests'
        return 1
    fi
}

_node_cli_cmd_list() {
    local core="" proto="" as_json=0 show_secrets=0 all
    while (( $# )); do
        case "$1" in
            --core) [[ $# -ge 2 ]] || { _node_cli_err '--core requires a value'; return 2; }; core=$(_node_cli_norm_core "$2") || { _node_cli_err "unknown core: $2"; return 2; }; shift 2 ;;
            --protocol) [[ $# -ge 2 ]] || { _node_cli_err '--protocol requires a value'; return 2; }; proto=$(_node_cli_norm_protocol "$2") || { _node_cli_err "unknown protocol: $2"; return 2; }; shift 2 ;;
            --json) as_json=1; shift ;;
            --show-secrets) show_secrets=1; shift ;;
            --help|-h) _node_cli_usage; return 0 ;;
            *) _node_cli_err "unknown list option: $1"; return 2 ;;
        esac
    done
    if [[ -n "$core" && -n "$proto" ]] && ! _node_cli_pair_supported "$core" "$proto"; then
        _node_cli_err "unsupported core/protocol: $core/$proto"; return 2
    fi
    all=$(_node_cli_collect "$core" "$proto") || return 1
    if [[ "$as_json" == "1" ]]; then
        printf '%s' "$all" | _node_cli_maybe_redact "$show_secrets" | jq -c \
            --argjson version "$_NODE_CLI_VERSION" '{api_version:$version, count:length, items:.}'
        return
    fi
    printf '%-10s %-12s %-28s %-7s\n' CORE PROTOCOL TAG PORT
    printf '%s' "$all" | jq -r '.[] | [.core,.protocol,.tag,(.port // "-")] | @tsv' | \
        while IFS=$'\t' read -r c p t po; do printf '%-10s %-12s %-28s %-7s\n' "$c" "$p" "$t" "$po"; done
}

_node_cli_cmd_show() {
    local tag="" core="" proto="" as_json=0 show_secrets=0 item display positional_core positional_proto
    if (( $# >= 3 )) && positional_core=$(_node_cli_norm_core "$1" 2>/dev/null) \
        && positional_proto=$(_node_cli_norm_protocol "$2" 2>/dev/null) \
        && _node_cli_pair_supported "$positional_core" "$positional_proto"; then
        core="$positional_core"; proto="$positional_proto"; tag="$3"; shift 3
    else
        tag="${1:-}"; shift || true
    fi
    [[ -n "$tag" && "$tag" != --* ]] || { _node_cli_err 'show requires TAG'; return 2; }
    while (( $# )); do
        case "$1" in
            --core) core=$(_node_cli_norm_core "${2:-}") || { _node_cli_err "unknown core: ${2:-}"; return 2; }; shift 2 ;;
            --protocol) proto=$(_node_cli_norm_protocol "${2:-}") || { _node_cli_err "unknown protocol: ${2:-}"; return 2; }; shift 2 ;;
            --json) as_json=1; shift ;;
            --show-secrets) show_secrets=1; shift ;;
            *) _node_cli_err "unknown show option: $1"; return 2 ;;
        esac
    done
    item=$(_node_cli_find "$tag" "$core" "$proto") || return 1
    display=$(printf '%s' "$item" | _node_cli_maybe_redact "$show_secrets") || return 1
    if [[ "$as_json" == "1" ]]; then
        printf '%s' "$display" | jq -c --argjson version "$_NODE_CLI_VERSION" '{api_version:$version,item:.}'
    else
        printf '%s\n' "$display" | jq -r '
          "ID:       \(.id)",
          "Core:     \(.core)",
          "Protocol: \(.protocol)",
          (.node | to_entries[] | "\(.key): \(.value | if type == "array" or type == "object" then tojson else tostring end)")'
    fi
}

_node_cli_parse_mutation() {
    # Outputs a shell-safe JSON parser state consumed by add/update. Positional
    # tag is passed as $1 (possibly empty), remaining arguments follow.
    local tag="$1"; shift
    local core="" proto="" input="" store_only=0 replace=0 if_exists=0 yes=0 as_json=0 show_secrets=0
    local mount443=0 skip_probe=0
    local json='{}' arg key value
    local -a sets=() sets_json=() unsets=()
    while (( $# )); do
        arg="$1"
        case "$arg" in
            --core) [[ $# -ge 2 ]] || { _node_cli_err '--core requires a value'; return 2; }; core=$(_node_cli_norm_core "$2") || { _node_cli_err "unknown core: $2"; return 2; }; shift 2 ;;
            --protocol) [[ $# -ge 2 ]] || { _node_cli_err '--protocol requires a value'; return 2; }; proto=$(_node_cli_norm_protocol "$2") || { _node_cli_err "unknown protocol: $2"; return 2; }; shift 2 ;;
            --input) [[ $# -ge 2 ]] || { _node_cli_err '--input requires FILE or -'; return 2; }; input="$2"; shift 2 ;;
            --data) [[ $# -ge 2 ]] || { _node_cli_err '--data requires JSON or @FILE'; return 2; }; input="$2"; shift 2 ;;
            --set) [[ $# -ge 2 && "$2" == *=* ]] || { _node_cli_err '--set requires KEY=VALUE'; return 2; }; sets+=("$2"); shift 2 ;;
            --set-json) [[ $# -ge 2 && "$2" == *=* ]] || { _node_cli_err '--set-json requires KEY=JSON'; return 2; }; sets_json+=("$2"); shift 2 ;;
            --unset) [[ $# -ge 2 ]] || { _node_cli_err '--unset requires KEY'; return 2; }; unsets+=("$2"); shift 2 ;;
            --store-only|--no-apply) store_only=1; shift ;;
            --replace) replace=1; shift ;;
            --if-exists) if_exists=1; shift ;;
            --yes|-y) yes=1; shift ;;
            --json) as_json=1; shift ;;
            --show-secrets) show_secrets=1; shift ;;
            --mount-443) mount443=1; shift ;;
            --skip-dest-probe) skip_probe=1; shift ;;
            --tag) [[ $# -ge 2 ]] || { _node_cli_err '--tag requires a value'; return 2; }; tag="$2"; shift 2 ;;
            --*)
                key=${arg#--}
                if ! _node_cli_is_field_opt "$key"; then _node_cli_err "unknown option: $arg"; return 2; fi
                [[ $# -ge 2 ]] || { _node_cli_err "$arg requires a value"; return 2; }
                sets+=("$(_node_cli_field_name "$key")=$2"); shift 2
                ;;
            *)
                if [[ -z "$tag" ]]; then tag="$arg"; shift
                else _node_cli_err "unexpected argument: $arg"; return 2
                fi
                ;;
        esac
    done
    if [[ -n "$input" ]]; then
        json=$(_node_cli_load_input "$input") || return 2
    fi
    [[ -n "$tag" ]] && json=$(_node_cli_set_value "$json" tag "$tag") || true
    for arg in "${sets[@]}"; do
        key=${arg%%=*}; value=${arg#*=}
        key=$(_node_cli_field_name "$key")
        json=$(_node_cli_set_value "$json" "$key" "$value") || { _node_cli_err "invalid value for $key"; return 2; }
    done
    for arg in "${sets_json[@]}"; do
        key=${arg%%=*}; value=${arg#*=}
        key=$(_node_cli_field_name "$key")
        json=$(_node_cli_set_value "$json" "$key" "$value" 1) || { _node_cli_err "invalid JSON value for $key"; return 2; }
    done
    for key in "${unsets[@]}"; do
        key=$(_node_cli_field_name "$key")
        json=$(printf '%s' "$json" | jq -c --arg k "$key" 'del(.[$k])') || return 2
    done
    jq -cn --arg core "$core" --arg proto "$proto" --argjson node "$json" \
        --argjson store_only "$store_only" --argjson replace "$replace" \
        --argjson if_exists "$if_exists" --argjson yes "$yes" --argjson out_json "$as_json" \
        --argjson show_secrets "$show_secrets" --argjson mount443 "$mount443" \
        --argjson skip_probe "$skip_probe" \
        '{core:$core,protocol:$proto,node:$node,
          store_only:($store_only == 1), replace:($replace == 1),
          if_exists:($if_exists == 1), yes:($yes == 1), json:($out_json == 1),
          show_secrets:($show_secrets == 1), mount_443:($mount443 == 1),
          skip_dest_probe:($skip_probe == 1)}'
}

_node_cli_cmd_add() {
    local state core proto node path old existing tag port new envelope changed
    if (( $# >= 2 )) && core=$(_node_cli_norm_core "$1" 2>/dev/null) \
        && proto=$(_node_cli_norm_protocol "$2" 2>/dev/null) \
        && _node_cli_pair_supported "$core" "$proto"; then
        shift 2
        set -- --core "$core" --protocol "$proto" "$@"
    fi
    state=$(_node_cli_parse_mutation "" "$@") || return $?
    _node_cli_require_root_unless_store_only "$state" || return 1
    core=$(printf '%s' "$state" | jq -r '.core'); proto=$(printf '%s' "$state" | jq -r '.protocol')
    [[ -n "$core" && -n "$proto" ]] || { _node_cli_err 'add requires --core and --protocol'; return 2; }
    _node_cli_pair_supported "$core" "$proto" || { _node_cli_err "unsupported core/protocol: $core/$proto"; return 2; }
    node=$(printf '%s' "$state" | jq -c '.node')
    if ! printf '%s' "$node" | jq -e '.port != null' >/dev/null; then _node_cli_err 'add requires --port or input.port'; return 2; fi
    local store_only mount_key="" old_mount_key="" old_port=""
    store_only=$(printf '%s' "$state" | jq -r '.store_only')
    _NODE_CLI_SKIP_PROBE=$(printf '%s' "$state" | jq -r '.skip_dest_probe | if . then 1 else 0 end')
    _NODE_CLI_MOUNT443=0
    if [[ "$(printf '%s' "$state" | jq -r '.mount_443')" == "true" ]]; then
        _node_cli_fronted_pair "$core" "$proto" || { _node_cli_err "--mount-443 is not available for $core/$proto"; return 2; }
        _NODE_CLI_MOUNT443=1
        node=$(printf '%s' "$node" | jq -c '.listen_addr = "127.0.0.1" | .public_port = 443')
    fi
    _node_cli_lock_acquire || return 1
    path=$(_node_cli_store_path "$core" "$proto")
    old=$(_node_cli_read_store "$path") || { _node_cli_lock_release; return 1; }
    tag=$(printf '%s' "$node" | jq -r --arg fallback "${core}-${proto}-1" '.tag // $fallback')
    existing=$(printf '%s' "$old" | jq -c --arg tag "$tag" 'first(.[] | select(.tag == $tag)) // empty')
    # Preserve generated credentials on retries. An add request that repeats the
    # desired public fields therefore resolves to the exact existing node.
    [[ -n "$existing" ]] && node=$(jq -cn --argjson old "$existing" --argjson patch "$node" '$old * $patch')
    # mKCP carries VLESS without TLS, and Xray clients from v26.7.7 on refuse
    # that towards a public address ("vless without TLS or other encryption is
    # prohibited"): a new mKCP node gets VLESS Encryption unless --vless-enc
    # none asks for the plaintext form older clients still take.
    if [[ -z "$existing" && "$core/$proto" == xray/xhttp ]] \
        && printf '%s' "$node" | jq -e '.mode == "mkcp" and ((.vless_enc // "") == "") and ((.vless_decryption // "") == "")' >/dev/null; then
        node=$(printf '%s' "$node" | jq -c '.vless_enc = "x25519"')
    fi
    node=$(_node_cli_defaults "$core" "$proto" "$node") || { _node_cli_lock_release; return 1; }
    if [[ "$store_only" != "true" ]]; then
        node=$(_node_cli_tls_auto "$core" "$proto" "$node") || { _node_cli_lock_release; return 2; }
    fi
    node=$(_node_cli_ech "$core" "$proto" "$node") || { _node_cli_lock_release; return 2; }
    _node_cli_validate "$core" "$proto" "$node" add || { _node_cli_lock_release; return 2; }
    # after the schema: what is wrong with the request itself is more useful
    # to hear than a missing certificate
    if [[ "$store_only" != "true" ]]; then
        _node_cli_xray_cert_check "$core" "$proto" "$node" || { _node_cli_lock_release; return 2; }
        _node_cli_bbr_check "$core" "$proto" "$node" || { _node_cli_lock_release; return 2; }
        _node_cli_pmtud_check "$core" "$proto" "$node" || { _node_cli_lock_release; return 2; }
    fi
    tag=$(printf '%s' "$node" | jq -r '.tag'); port=$(printf '%s' "$node" | jq -r '.port')
    if [[ "$store_only" != "true" ]]; then
        _node_cli_probe_reality "$core" "$proto" "$node" "$existing" || { _node_cli_lock_release; return 2; }
    fi
    if [[ -n "$existing" ]]; then
        if jq -e --argjson a "$existing" --argjson b "$node" -n '$a == $b' >/dev/null; then
            _node_cli_lock_release
            envelope=$(printf '[%s]' "$existing" | _node_cli_envelope "$core" "$proto" | jq -c '.[0]')
            _node_cli_result unchanged "$envelope" "$(printf '%s' "$state" | jq -r '.json|if . then 1 else 0 end')" "$(printf '%s' "$state" | jq -r '.show_secrets|if . then 1 else 0 end')"
            return 0
        fi
        if [[ "$(printf '%s' "$state" | jq -r '.replace')" != "true" ]]; then
            _node_cli_lock_release; _node_cli_err "node already exists with different data: $core/$proto/$tag (use --replace)"; return 1
        fi
    fi
    _node_cli_check_port_conflict "$core" "$proto" "$tag" "$port" || { _node_cli_lock_release; return 1; }
    if [[ -z "$existing" && "$(printf '%s' "$state" | jq -r '.store_only')" != "true" ]] \
        && _node_cli_port_is_listening "$port" "$(_node_cli_transport "$proto")"; then
        _node_cli_lock_release
        _node_cli_err "$(_node_cli_transport "$proto") port $port is already held by a running process"
        return 1
    fi
    if [[ "$store_only" != "true" ]] && _node_cli_is_mounted "$core" "$proto" "$node"; then
        mount_key=$(_node_cli_sni_key "$proto" "$node")
        [[ -n "$mount_key" ]] || { _node_cli_lock_release; _node_cli_err "a node on the shared 443 needs its SNI (--server-name, --domain or --sni)"; return 2; }
        _node_cli_mount_precheck "$mount_key" "$port" \
            "$([[ -n "$existing" ]] && printf '%s' "$existing" | jq -r '.port')" || { _node_cli_lock_release; return 1; }
        if [[ -n "$existing" ]] && _node_cli_is_mounted "$core" "$proto" "$existing"; then
            old_mount_key=$(_node_cli_sni_key "$proto" "$existing")
            old_port=$(printf '%s' "$existing" | jq -r '.port')
        fi
    fi
    if [[ "$store_only" != "true" ]]; then
        # The core has to be there before the exit: preparing one registers WARP
        # or dials the residential line, and _node_cli_commit_store would only
        # then find the core missing — leaving that behind for a node that was
        # never made, and reporting it as an exit failure.
        _node_cli_require_core "$core" || { _node_cli_lock_release; return 1; }
        # the exit next: a residential line that does not answer leaves nothing half made
        _node_cli_exit_prepare "$core" "$node" || { _node_cli_lock_release; return 1; }
    fi
    new=$(printf '%s' "$old" | jq -c --arg tag "$tag" --argjson node "$node" 'del(.[] | select(.tag == $tag)) + [$node]') || { _node_cli_lock_release; return 1; }
    _node_cli_commit_store "$core" "$proto" "$new" "$(printf '%s' "$state" | jq -r '.store_only|if . then 1 else 0 end')" || { _node_cli_lock_release; return 1; }
    if [[ -n "$mount_key" ]]; then
        if ! _node_cli_mount_apply "$mount_key" "$port"; then
            # Nothing may point at a route Nginx refused: put the node store back.
            _node_cli_commit_store "$core" "$proto" "$old" 0 >/dev/null 2>&1 || true
            _node_cli_lock_release
            _node_cli_err "Nginx did not accept the 443 route for $mount_key; the node was rolled back"
            return 1
        fi
        [[ -n "$old_mount_key" && "$old_mount_key" != "$mount_key" ]] && _node_cli_mount_remove "$old_mount_key" "$old_port"
    fi
    _node_cli_lock_release
    if [[ "$store_only" != "true" ]]; then
        _node_cli_fw_open "$proto" "$node"
        if [[ -n "$existing" && "$(printf '%s' "$existing" | jq -r '.port')" != "$port" ]]; then
            _node_cli_fw_close "$existing"
        fi
        _node_cli_exit_rules "$core" "$tag" "$node" || return 1
    fi
    envelope=$(printf '[%s]' "$node" | _node_cli_envelope "$core" "$proto" | jq -c '.[0]')
    changed=created; [[ -n "$existing" ]] && changed=replaced
    _node_cli_result "$changed" "$envelope" "$(printf '%s' "$state" | jq -r '.json|if . then 1 else 0 end')" "$(printf '%s' "$state" | jq -r '.show_secrets|if . then 1 else 0 end')"
}

_node_cli_cmd_update() {
    local tag="" state filter_core filter_proto item core proto old_node patch node path store new port envelope positional_core positional_proto
    if (( $# >= 3 )) && positional_core=$(_node_cli_norm_core "$1" 2>/dev/null) \
        && positional_proto=$(_node_cli_norm_protocol "$2" 2>/dev/null) \
        && _node_cli_pair_supported "$positional_core" "$positional_proto"; then
        tag="$3"; shift 3
        set -- --core "$positional_core" --protocol "$positional_proto" "$@"
    else
        tag="${1:-}"; shift || true
    fi
    [[ -n "$tag" && "$tag" != --* ]] || { _node_cli_err 'update requires TAG'; return 2; }
    state=$(_node_cli_parse_mutation "$tag" "$@") || return $?
    _node_cli_require_root_unless_store_only "$state" || return 1
    filter_core=$(printf '%s' "$state" | jq -r '.core'); filter_proto=$(printf '%s' "$state" | jq -r '.protocol')
    item=$(_node_cli_find "$tag" "$filter_core" "$filter_proto") || return 1
    core=$(printf '%s' "$item" | jq -r '.core'); proto=$(printf '%s' "$item" | jq -r '.protocol')
    old_node=$(printf '%s' "$item" | jq -c '.node'); patch=$(printf '%s' "$state" | jq -c '.node | del(.tag)')
    node=$(jq -cn --argjson old "$old_node" --argjson patch "$patch" '$old * $patch') || return 1
    # 直连节点改端口时 public_port 必须跟着走：分享链接取的是 public_port // port，
    # 不同步就会导出一条指向旧端口的链接，节点在新端口上监听、客户端连不上。交互式
    # 的 *_modify_port 一直是这么做的，非交互路径此前漏了这一步。
    # 两个例外：挂 Nginx 的节点（listen_addr 127.0.0.1）public_port 是公网 443，
    # 与后端回环端口无关；调用方显式传了 --public-port 时以调用方为准。
    node=$(jq -cn --argjson old "$old_node" --argjson new "$node" --argjson patch "$patch" '
        if ($patch | has("public_port")) then $new
        elif ($new | has("public_port"))
             and (($new.listen_addr // "") != "127.0.0.1")
             and ($new.port != $old.port)
        then $new | .public_port = $new.port
        else $new end') || return 1
    # REALITY 改伪装域名时 server_names_raw 必须跟着走：它是原始的逗号清单，
    # 而 Xray 的 inbound 写的是 .server_names_raw // .server_name —— 只改
    # server_name 的话内核里仍是旧域名，客户端按新域名握手就连不上。
    # 调用方显式传了 --server-names-raw 时以调用方为准（多 SNI 的用法）。
    node=$(jq -cn --argjson new "$node" --argjson patch "$patch" '
        if ($patch | has("server_names_raw")) then $new
        elif ($patch | has("server_name")) and ($new | has("server_names_raw"))
        then $new | .server_names_raw = $new.server_name
        else $new end') || return 1
    if [[ "$(printf '%s' "$state" | jq -r '.store_only')" != "true" ]]; then
        node=$(_node_cli_tls_auto "$core" "$proto" "$node") || return 2
    fi
    node=$(_node_cli_ech "$core" "$proto" "$node") || return 2
    # a node that becomes mKCP gets VLESS Encryption as a new one does (see add)
    if [[ "$core/$proto" == xray/xhttp ]] && printf '%s' "$node" | jq -e --argjson o "$old_node" \
        '.mode == "mkcp" and $o.mode != "mkcp" and ((.vless_enc // "") == "") and ((.vless_decryption // "") == "")' >/dev/null; then
        node=$(printf '%s' "$node" | jq -c '.vless_enc = "x25519"')
    fi
    node=$(_node_cli_vless_enc "$core" "$proto" "$node" "$old_node") || return 2
    _node_cli_validate_update_side_effects "$core" "$proto" "$old_node" "$node" || return 2
    _node_cli_validate "$core" "$proto" "$node" update || return 2
    if [[ "$(printf '%s' "$state" | jq -r '.store_only')" != "true" ]]; then
        _node_cli_xray_cert_check "$core" "$proto" "$node" || return 2
        _node_cli_bbr_check "$core" "$proto" "$node" || return 2
        _node_cli_pmtud_check "$core" "$proto" "$node" || return 2
    fi
    port=$(printf '%s' "$node" | jq -r '.port')
    local upd_store_only mount_key="" old_mount_key="" old_port
    upd_store_only=$(printf '%s' "$state" | jq -r '.store_only')
    _NODE_CLI_SKIP_PROBE=$(printf '%s' "$state" | jq -r '.skip_dest_probe | if . then 1 else 0 end')
    if [[ "$upd_store_only" != "true" ]]; then
        _node_cli_probe_reality "$core" "$proto" "$node" "$old_node" || return 2
    fi
    if jq -e --argjson a "$old_node" --argjson b "$node" -n '$a == $b' >/dev/null; then
        _node_cli_result unchanged "$item" "$(printf '%s' "$state" | jq -r '.json|if . then 1 else 0 end')" "$(printf '%s' "$state" | jq -r '.show_secrets|if . then 1 else 0 end')"
        return 0
    fi
    _node_cli_lock_acquire || return 1
    _node_cli_check_port_conflict "$core" "$proto" "$tag" "$port" || { _node_cli_lock_release; return 1; }
    path=$(_node_cli_store_path "$core" "$proto"); store=$(_node_cli_read_store "$path") || { _node_cli_lock_release; return 1; }
    # Re-check under lock to avoid overwriting a concurrent change.
    if ! printf '%s' "$store" | jq -e --arg tag "$tag" --argjson old "$old_node" 'first(.[] | select(.tag == $tag)) == $old' >/dev/null; then
        _node_cli_lock_release; _node_cli_err "node changed concurrently: $core/$proto/$tag"; return 1
    fi
    if [[ "$upd_store_only" != "true" ]] && _node_cli_is_mounted "$core" "$proto" "$node"; then
        mount_key=$(_node_cli_sni_key "$proto" "$node")
        old_mount_key=$(_node_cli_sni_key "$proto" "$old_node")
        old_port=$(printf '%s' "$old_node" | jq -r '.port')
        if [[ "$mount_key" == "$old_mount_key" && "$port" == "$old_port" ]]; then
            mount_key=""   # routing unchanged
        else
            [[ -n "$mount_key" ]] || { _node_cli_lock_release; _node_cli_err "a node on the shared 443 needs its SNI"; return 2; }
            _node_cli_mount_precheck "$mount_key" "$port" "$old_port" || { _node_cli_lock_release; return 1; }
        fi
    fi
    if [[ "$upd_store_only" != "true" ]]; then
        _node_cli_require_core "$core" || { _node_cli_lock_release; return 1; }
        _node_cli_exit_prepare "$core" "$node" || { _node_cli_lock_release; return 1; }
    fi
    new=$(printf '%s' "$store" | jq -c --arg tag "$tag" --argjson node "$node" 'map(if .tag == $tag then $node else . end)') || { _node_cli_lock_release; return 1; }
    _node_cli_commit_store "$core" "$proto" "$new" "$(printf '%s' "$state" | jq -r '.store_only|if . then 1 else 0 end')" || { _node_cli_lock_release; return 1; }
    if [[ -n "$mount_key" ]]; then
        if ! _node_cli_mount_apply "$mount_key" "$port"; then
            _node_cli_commit_store "$core" "$proto" "$store" 0 >/dev/null 2>&1 || true
            _node_cli_lock_release
            _node_cli_err "Nginx did not accept the 443 route for $mount_key; the update was rolled back"
            return 1
        fi
        [[ "$old_mount_key" != "$mount_key" ]] && _node_cli_mount_remove "$old_mount_key" "$old_port"
    fi
    _node_cli_lock_release
    if [[ "$upd_store_only" != "true" ]]; then
        _node_cli_fw_open "$proto" "$node"
        if [[ "$(printf '%s' "$old_node" | jq -r '.port')" != "$port" ]]; then
            _node_cli_fw_close "$old_node"
        fi
        _node_cli_exit_rules "$core" "$tag" "$node" || return 1
    fi
    envelope=$(printf '[%s]' "$node" | _node_cli_envelope "$core" "$proto" | jq -c '.[0]')
    _node_cli_result updated "$envelope" "$(printf '%s' "$state" | jq -r '.json|if . then 1 else 0 end')" "$(printf '%s' "$state" | jq -r '.show_secrets|if . then 1 else 0 end')"
}

_node_cli_cmd_delete() {
    local tag="" state core_filter proto_filter item core proto path store old_node new envelope positional_core positional_proto
    if (( $# >= 3 )) && positional_core=$(_node_cli_norm_core "$1" 2>/dev/null) \
        && positional_proto=$(_node_cli_norm_protocol "$2" 2>/dev/null) \
        && _node_cli_pair_supported "$positional_core" "$positional_proto"; then
        tag="$3"; shift 3
        set -- --core "$positional_core" --protocol "$positional_proto" "$@"
    else
        tag="${1:-}"; shift || true
    fi
    [[ -n "$tag" && "$tag" != --* ]] || { _node_cli_err 'delete requires TAG'; return 2; }
    state=$(_node_cli_parse_mutation "$tag" "$@") || return $?
    _node_cli_require_root_unless_store_only "$state" || return 1
    if [[ "$(printf '%s' "$state" | jq -r '.yes')" != "true" ]]; then _node_cli_err 'delete requires --yes'; return 2; fi
    core_filter=$(printf '%s' "$state" | jq -r '.core'); proto_filter=$(printf '%s' "$state" | jq -r '.protocol')
    if ! item=$(_node_cli_find "$tag" "$core_filter" "$proto_filter" \
        "$([[ "$(printf '%s' "$state" | jq -r '.if_exists')" == "true" ]] && printf 1 || printf 0)"); then
        if [[ "$(printf '%s' "$state" | jq -r '.if_exists')" == "true" ]]; then
            if [[ "$(printf '%s' "$state" | jq -r '.json')" == "true" ]]; then jq -cn --arg tag "$tag" '{status:"absent",tag:$tag}'; else printf 'absent: %s\n' "$tag"; fi
            return 0
        fi
        return 1
    fi
    core=$(printf '%s' "$item" | jq -r '.core'); proto=$(printf '%s' "$item" | jq -r '.protocol'); old_node=$(printf '%s' "$item" | jq -c '.node')
    _node_cli_lock_acquire || return 1
    path=$(_node_cli_store_path "$core" "$proto"); store=$(_node_cli_read_store "$path") || { _node_cli_lock_release; return 1; }
    if ! printf '%s' "$store" | jq -e --arg tag "$tag" --argjson old "$old_node" 'first(.[] | select(.tag == $tag)) == $old' >/dev/null; then
        _node_cli_lock_release; _node_cli_err "node changed concurrently: $core/$proto/$tag"; return 1
    fi
    new=$(printf '%s' "$store" | jq -c --arg tag "$tag" 'del(.[] | select(.tag == $tag))') || { _node_cli_lock_release; return 1; }
    _node_cli_commit_store "$core" "$proto" "$new" "$(printf '%s' "$state" | jq -r '.store_only|if . then 1 else 0 end')" || { _node_cli_lock_release; return 1; }
    if [[ "$(printf '%s' "$state" | jq -r '.store_only')" != "true" ]] \
        && _node_cli_is_mounted "$core" "$proto" "$old_node"; then
        _node_cli_mount_remove "$(_node_cli_sni_key "$proto" "$old_node")" "$(printf '%s' "$old_node" | jq -r '.port')"
    fi
    _node_cli_lock_release
    _node_cli_cleanup_deleted_metadata "$tag"
    if [[ "$(printf '%s' "$state" | jq -r '.store_only')" != "true" ]]; then
        _node_cli_fw_close "$old_node"
        # its exit rule goes with it (the exit itself stays, other nodes may use it)
        source "$LIB_DIR/exit_cli.sh"
        if exit_node_has "$core" "$tag"; then exit_node_set "$core" "$tag" "" || true; fi
    fi
    envelope=$(printf '[%s]' "$old_node" | _node_cli_envelope "$core" "$proto" | jq -c '.[0]')
    _node_cli_result deleted "$envelope" "$(printf '%s' "$state" | jq -r '.json|if . then 1 else 0 end')" "$(printf '%s' "$state" | jq -r '.show_secrets|if . then 1 else 0 end')"
}

_node_cli_urlencode() { jq -nr --arg v "$1" '$v | @uri'; }

_node_cli_ss_userinfo() {
    printf '%s' "$1:$2" | openssl base64 -A | tr '+/' '-_' | tr -d '='
}

# The query a self-signed node's link adds (see psm_node_pins in common.sh):
# the old skip flag for the clients that still honour it, and the
# certificate's SHA-256 for those that pin it — pcs in vless:// and trojan://
# (Xray's share-link standard, also read by mihomo), pinSHA256 in hysteria2://
# (Hysteria's), hpkp in anytls:// (mihomo's).
_node_cli_selfsigned_q() {   # <node json> <flag=value> <pin parameter>
    [[ "$(printf '%s' "$1" | jq -r '.insecure // 0 | tostring')" =~ ^(1|true)$ ]] || return 0
    [[ -n "$2" ]] && printf '&%s' "$2"
    psm_pin_q "$1" "$3"
}

_node_cli_export_uri() {
    local core="$1" proto="$2" n="$3" server="$4"
    local tag port uuid flow sn pbk sid mode path domain method password sni insecure obfs psk version username
    tag=$(printf '%s' "$n" | jq -r '.tag'); port=$(printf '%s' "$n" | jq -r '.public_port // .port')
    case "$proto" in
        reality)
            uuid=$(printf '%s' "$n" | jq -r '.uuid'); flow=$(printf '%s' "$n" | jq -r '.flow'); sn=$(printf '%s' "$n" | jq -r '.server_name')
            pbk=$(printf '%s' "$n" | jq -r '.public_key'); sid=$(printf '%s' "$n" | jq -r '.short_ids[0]')
            printf 'vless://%s@%s:%s?encryption=%s&flow=%s&security=reality&sni=%s&fp=chrome&pbk=%s&sid=%s&type=tcp#%s\n' \
                "$uuid" "$server" "$port" "$(_node_cli_urlencode "$(printf '%s' "$n" | jq -r '.vless_encryption // "none"')")" \
                "$(_node_cli_urlencode "$flow")" "$(_node_cli_urlencode "$sn")" \
                "$(_node_cli_urlencode "$pbk")" "$(_node_cli_urlencode "$sid")" "$(_node_cli_urlencode "PSM-$tag")"
            ;;
        vision)
            uuid=$(printf '%s' "$n" | jq -r '.uuid'); flow=$(printf '%s' "$n" | jq -r '.flow'); domain=$(printf '%s' "$n" | jq -r '.domain')
            printf 'vless://%s@%s:%s?encryption=%s&flow=%s&security=tls&sni=%s&type=tcp#%s\n' \
                "$uuid" "$server" "$port" "$(_node_cli_urlencode "$(printf '%s' "$n" | jq -r '.vless_encryption // "none"')")" \
                "$(_node_cli_urlencode "$flow")" "$(_node_cli_urlencode "$domain")" "$(_node_cli_urlencode "PSM-$tag")"
            ;;
        xhttp)
            # 与交互菜单共用同一个链接构造器。此前这里另写了一份，只认 reality-layer /
            # grpc / ws，h2、httpupgrade、mkcp、Reality+gRPC 都被导出成错误的 xhttp 链接。
            declare -f _xhttp_share_uri &>/dev/null || source "$LIB_DIR/xray/xhttp.sh"
            _xhttp_share_uri "$n" "$server" "$port"
            ;;
        vless)
            uuid=$(printf '%s' "$n" | jq -r '.uuid')
            flow=$(printf '%s' "$n" | jq -r '.flow // ""')
            path=$(printf '%s' "$n" | jq -r '.path // "/"')
            sni=$(printf '%s' "$n" | jq -r '.sni')
            mode=$(printf '%s' "$n" | jq -r '.transport // "tcp"')
            # 链接里的 type 用客户端认识的名字：sing-box 内部叫 http，客户端叫 h2
            [[ "$mode" == "http" ]] && mode="h2"
            printf 'vless://%s@%s:%s?encryption=%s&security=tls&sni=%s&type=%s' \
                "$uuid" "$server" "$port" "$(_node_cli_urlencode "$(printf '%s' "$n" | jq -r '.vless_encryption // "none"')")" \
                "$(_node_cli_urlencode "$sni")" "$mode"
            [[ -n "$flow" ]] && printf '&flow=%s' "$(_node_cli_urlencode "$flow")"
            # a self-signed certificate: the client must be told to accept it (as the menus' links do)
            _node_cli_selfsigned_q "$n" 'allowInsecure=1' pcs
            case "$mode" in
                grpc)          printf '&serviceName=%s' "$(_node_cli_urlencode "${path#/}")" ;;
                ws|h2|httpupgrade|xhttp)
                               printf '&path=%s&host=%s' "$(_node_cli_urlencode "$path")" "$(_node_cli_urlencode "$sni")" ;;
            esac
            printf '#%s\n' "$(_node_cli_urlencode "PSM-$tag")"
            ;;
        socks)
            # 仅本机的节点没有可分享的地址（127.0.0.1 换台机器就连不上），
            # 导出一条会误导人的链接不如明确报错。
            username=$(printf '%s' "$n" | jq -r '.username // ""')
            password=$(printf '%s' "$n" | jq -r '.password // ""')
            if [[ "$(printf '%s' "$n" | jq -r '.listen_addr // ""')" == "127.0.0.1" ]]; then
                _node_cli_err 'a loopback-only SOCKS5 node has no shareable address; it is reachable at 127.0.0.1 on the host itself'
                return 2
            fi
            if [[ -n "$username" ]]; then
                printf 'socks://%s@%s:%s#%s\n' \
                    "$(printf '%s:%s' "$username" "$password" | openssl base64 -A)" \
                    "$server" "$port" "$(_node_cli_urlencode "PSM-$tag")"
            else
                printf 'socks://%s:%s#%s\n' "$server" "$port" "$(_node_cli_urlencode "PSM-$tag")"
            fi
            ;;
        vmess)
            # VMess 没有查询参数式 URI：vmess:// 后跟一段 base64 的 JSON
            # （v2rayN 事实标准）。字段名是固定三字母缩写，改名客户端解析不出来。
            uuid=$(printf '%s' "$n" | jq -r '.uuid')
            path=$(printf '%s' "$n" | jq -r '.path')
            domain=$(printf '%s' "$n" | jq -r '.domain // .sni // ""')
            # a self-signed certificate (sing-box / mihomo without a domain): v2rayN's
            # "insecure" and "pcs" keys, as in its own vmess:// links
            local vpin=""
            if [[ "$(printf '%s' "$n" | jq -r '.insecure // 0 | tostring')" =~ ^(1|true)$ ]]; then
                vpin=$(psm_cert_sha256 "$(printf '%s' "$n" | jq -r '.cert_path // ""')") || vpin="-"
            fi
            jq -nc --arg ps "PSM-$tag" --arg add "$server" --arg port "$port" \
                --arg id "$uuid" --arg host "$domain" --arg path "$path" --arg pin "$vpin" \
                '{v:"2", ps:$ps, add:$add, port:$port, id:$id, aid:"0", scy:"auto",
                  net:"ws", type:"none", host:$host, path:$path, tls:"tls", sni:$host}
                 + (if $pin == "" then {} else {insecure: "1"} end)
                 + (if $pin == "" or $pin == "-" then {} else {pcs: $pin} end)' \
                | openssl base64 -A | sed 's|^|vmess://|'
            printf '\n'
            ;;
        trojan)
            password=$(printf '%s' "$n" | jq -r '.password')
            # Xray 侧字段是 domain（真实证书域名），sing-box / mihomo 侧是 sni
            # （可能是自签证书的伪装域名）。取到哪个用哪个。
            domain=$(printf '%s' "$n" | jq -r '.domain // .sni // ""')
            # alpn 只在服务端真的配了才写进链接。Xray 侧的 tlsSettings 显式声明了
            # ["h2","http/1.1"]；sing-box / mihomo 侧的 tls 块没有 alpn 字段，此时
            # 让客户端宣告一组服务端并不限制的协议只会徒增握手不一致的风险。
            printf 'trojan://%s@%s:%s?security=tls&sni=%s&type=tcp' \
                "$(_node_cli_urlencode "$password")" "$server" "$port" \
                "$(_node_cli_urlencode "$domain")"
            [[ "$core" == "xray" ]] && printf '&alpn=%s' "$(_node_cli_urlencode "h2,http/1.1")"
            _node_cli_selfsigned_q "$n" 'allowInsecure=1' pcs
            printf '#%s\n' "$(_node_cli_urlencode "PSM-$tag")"
            ;;
        ss2022)
            # ShadowTLS 节点没有客户端公认的 URI 写法；不带插件的 ss:// 会让客户端
            # 直连一个它握不上的端口，所以明确拒绝并指向 surge 格式。
            if [[ -n "$(printf '%s' "$n" | jq -r '.stls_password // empty')" ]]; then
                _node_cli_err 'ShadowTLS nodes have no standard URI; use --format surge (or the menu for a Clash snippet)'
                return 2
            fi
            method=$(printf '%s' "$n" | jq -r '.method'); password=$(printf '%s' "$n" | jq -r '.password')
            printf 'ss://%s@%s:%s#%s\n' "$(_node_cli_ss_userinfo "$method" "$password")" "$server" "$port" "$(_node_cli_urlencode "PSM-$tag")"
            ;;
        hysteria2)
            # Xray 节点走模块自己的构造器：自签名证书时它会附上 pinSHA256
            if [[ "$core" == "xray" ]]; then
                declare -f _xhy2_share_uri &>/dev/null || source "$LIB_DIR/xray/hysteria2.sh"
                _xhy2_share_uri "$n" "$server"
                return 0
            fi
            password=$(printf '%s' "$n" | jq -r '.password'); sni=$(printf '%s' "$n" | jq -r '.sni'); insecure=$(printf '%s' "$n" | jq -r '.insecure | if . == true then 1 elif . == false then 0 else . end'); obfs=$(printf '%s' "$n" | jq -r '.obfs_pass // ""')
            printf 'hysteria2://%s@%s:%s%s?insecure=%s&sni=%s' "$(_node_cli_urlencode "$password")" "$server" "$port" \
                "$(printf '%s' "$n" | jq -r '(.hop_ports // "") | if . == "" then "" else "," + . end')" "$insecure" "$(_node_cli_urlencode "$sni")"
            _node_cli_selfsigned_q "$n" '' pinSHA256
            [[ -n "$obfs" ]] && printf '&obfs=%s&obfs-password=%s' \
                "$(printf '%s' "$n" | jq -r '.obfs_type // "salamander"')" "$(_node_cli_urlencode "$obfs")"
            printf '#%s\n' "$(_node_cli_urlencode "PSM-$tag")"
            ;;
        anytls)
            password=$(printf '%s' "$n" | jq -r '.password'); sni=$(printf '%s' "$n" | jq -r '.sni'); insecure=$(printf '%s' "$n" | jq -r '.insecure | if . == true then 1 elif . == false then 0 else . end')
            printf 'anytls://%s@%s:%s?insecure=%s&sni=%s' "$(_node_cli_urlencode "$password")" "$server" "$port" "$insecure" "$(_node_cli_urlencode "$sni")"
            _node_cli_selfsigned_q "$n" '' hpkp
            printf '#%s\n' "$(_node_cli_urlencode "PSM-$tag")"
            ;;
        wireguard)
            # No URI for WireGuard: one wg-quick file per client
            declare -f sb_wg_client_conf &>/dev/null || source "$LIB_DIR/singbox/wireguard.sh"
            local wh; for wh in $(printf '%s' "$n" | jq -r '.peers[].host'); do
                sb_wg_client_conf "$n" "$wh" "$server"; echo
            done
            ;;
        tuic)
            if [[ "$core" == "mihomo" ]]; then
                declare -f _mh_tuic_link &>/dev/null || source "$LIB_DIR/mihomo/tuic.sh"
                _mh_tuic_link "$n" "$server"
            else
                declare -f _sb_tuic_link &>/dev/null || source "$LIB_DIR/singbox/tuic.sh"
                _sb_tuic_link "$n" "$server"
            fi
            ;;
        snell)
            _node_cli_err 'Snell has no standard URI; use --format surge'
            return 2
            ;;
    esac
}

_node_cli_export_surge() {
    local n="$1" server="$2" proto="${3:-snell}" tag port psk version om oh line spw ssni
    tag=$(printf '%s' "$n" | jq -r '.tag'); port=$(printf '%s' "$n" | jq -r '.port')
    spw=$(printf '%s' "$n" | jq -r '.stls_password // ""'); ssni=$(printf '%s' "$n" | jq -r '.stls_sni // ""')
    if [[ "$proto" == "ss2022" ]]; then
        line="PSM-${tag} = ss, ${server}, ${port}, encrypt-method=$(printf '%s' "$n" | jq -r '.method'), password=$(printf '%s' "$n" | jq -r '.password')"
    else
        psk=$(printf '%s' "$n" | jq -r '.psk'); version=$(printf '%s' "$n" | jq -r '.version')
        om=$(printf '%s' "$n" | jq -r '.obfs_mode // ""'); oh=$(printf '%s' "$n" | jq -r '.obfs_host // ""')
        line="PSM-${tag} = snell, ${server}, ${port}, psk=${psk}, version=${version}"
        [[ -n "$om" ]] && line="${line}, obfs=${om}, obfs-host=${oh:-bing.com}"
    fi
    [[ -n "$spw" ]] && line="${line}, shadow-tls-password=${spw}, shadow-tls-sni=${ssni}, shadow-tls-version=3"
    printf '%s\n' "$line"
}

_node_cli_cmd_export() {
    local tag="" core="" proto="" format="" server="" item n positional_core positional_proto
    if (( $# >= 3 )) && positional_core=$(_node_cli_norm_core "$1" 2>/dev/null) \
        && positional_proto=$(_node_cli_norm_protocol "$2" 2>/dev/null) \
        && _node_cli_pair_supported "$positional_core" "$positional_proto"; then
        core="$positional_core"; proto="$positional_proto"; tag="$3"; shift 3
    else
        tag="${1:-}"; shift || true
    fi
    [[ -n "$tag" && "$tag" != --* ]] || { _node_cli_err 'export requires TAG'; return 2; }
    while (( $# )); do
        case "$1" in
            --core) core=$(_node_cli_norm_core "${2:-}") || { _node_cli_err "unknown core: ${2:-}"; return 2; }; shift 2 ;;
            --protocol) proto=$(_node_cli_norm_protocol "${2:-}") || { _node_cli_err "unknown protocol: ${2:-}"; return 2; }; shift 2 ;;
            --format) format="${2:-}"; shift 2 ;;
            --server) server="${2:-}"; shift 2 ;;
            --json) format=json; shift ;;
            *) _node_cli_err "unknown export option: $1"; return 2 ;;
        esac
    done
    item=$(_node_cli_find "$tag" "$core" "$proto") || return 1
    core=$(printf '%s' "$item" | jq -r '.core'); proto=$(printf '%s' "$item" | jq -r '.protocol'); n=$(printf '%s' "$item" | jq -c '.node')
    [[ -n "$format" ]] || { [[ "$proto" == "snell" ]] && format=surge || format=uri; }
    if [[ "$format" == "json" ]]; then printf '%s\n' "$item" | jq -c '.'; return; fi
    [[ -n "$server" ]] || server=$(get_ipv4 2>/dev/null || true)
    [[ -n "$server" ]] || { _node_cli_err 'could not determine public server address; pass --server'; return 1; }
    case "$format" in
        uri) _node_cli_export_uri "$core" "$proto" "$n" "$server" ;;
        surge)
            [[ "$proto" == "snell" || "$proto" == "ss2022" ]] \
                || { _node_cli_err '--format surge is only available for Snell and SS2022'; return 2; }
            _node_cli_export_surge "$n" "$server" "$proto"
            ;;
        singbox|sing-box)
            # The node as one sing-box client outbound (the PSM panel's sing-box subscription)
            declare -f _sub_sb_outbound &>/dev/null || source "$LIB_DIR/subscribe.sh"
            local ob; ob=$(_sub_sb_outbound "$core" "$proto" "$n" "$server" "$tag" || true)
            [[ -n "$ob" ]] || { _node_cli_err "$core/$proto has no sing-box client outbound; use --format uri"; return 2; }
            printf '%s\n' "$ob" | jq -c '.'
            ;;
        clash|mihomo)
            # The node as one mihomo proxy (the PSM panel's Clash subscription)
            declare -f _sub_mh_proxy &>/dev/null || source "$LIB_DIR/subscribe.sh"
            local px; px=$(_sub_mh_proxy "$core" "$proto" "$n" "$server" "$tag" || true)
            [[ -n "$px" ]] || { _node_cli_err "$core/$proto has no mihomo proxy of its own (its share link imports as it is); use --format uri"; return 2; }
            printf '%s\n' "$px" | jq -c '.'
            ;;
        ech)
            # The ECH config clients need (mihomo ech-opts.config); not part of any share link
            printf '%s' "$n" | jq -er '.ech_config // empty' \
                || { _node_cli_err "$tag has no ECH; enable it with: psm node update $core $proto $tag --ech true"; return 1; }
            ;;
        *) _node_cli_err "unsupported export format: $format"; return 2 ;;
    esac
}

node_cli_main() {
    command -v jq >/dev/null 2>&1 || { _node_cli_err 'jq is required'; return 127; }
    [[ "${1:-}" == "node" ]] && shift
    local command="${1:-}"
    [[ -n "$command" ]] || { _node_cli_usage >&2; return 2; }
    shift
    case "$command" in
        list) _node_cli_cmd_list "$@" ;;
        show) _node_cli_cmd_show "$@" ;;
        add) _node_cli_cmd_add "$@" ;;
        update) _node_cli_cmd_update "$@" ;;
        delete|remove|rm) _node_cli_cmd_delete "$@" ;;
        export) _node_cli_cmd_export "$@" ;;
        help|--help|-h) _node_cli_usage ;;
        *) _node_cli_err "unknown command: $command"; _node_cli_usage >&2; return 2 ;;
    esac
}

psm_node_cli() { node_cli_main "$@"; }
